   SO PARA QUEM JA EXECUTOU OS SCRIPTS 01 A 03 DA ENTREGA ANTERIOR (SEM A COLUNA NOME_USUARIO E COM E-MAIL UNICO).
   QUEM VAI CRIAR O BANCO AGORA NAO PRECISA DESTE SCRIPT. */
IF EXISTS (SELECT 1 FROM SYS.KEY_CONSTRAINTS WHERE NAME = 'UQ_USUARIO_EMAIL' AND PARENT_OBJECT_ID = OBJECT_ID('DBO.USUARIO'))
    ALTER TABLE DBO.[USUARIO] DROP CONSTRAINT UQ_USUARIO_EMAIL;
GO
ALTER TABLE DBO.[USUARIO] ADD [NOME_USUARIO] NVARCHAR(60) NULL;
GO
-- SE JA HOUVER USUARIOS, PREENCHA O LOGIN DE CADA UM ANTES DO PROXIMO PASSO (EX.: UPDATE DBO.USUARIO SET NOME_USUARIO = 'FABRYCIO.CORREA' WHERE CODIGO_USUARIO = 1;)
ALTER TABLE DBO.[USUARIO] ALTER COLUMN [NOME_USUARIO] NVARCHAR(60) NOT NULL;
GO
ALTER TABLE DBO.[USUARIO] ADD CONSTRAINT UQ_USUARIO_NOME_USUARIO UNIQUE ([NOME_USUARIO]);
GO
