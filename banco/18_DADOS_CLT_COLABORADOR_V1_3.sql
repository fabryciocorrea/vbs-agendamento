-- =====================================================================
-- SCRIPT 18 - DADOS DA CARTEIRA DE TRABALHO (CLT) NO COLABORADOR (V1.3)
-- CAMPOS NOVOS (TODOS OPCIONAIS): CTPS (NUMERO, SERIE, UF, DATA DE EMISSAO), PIS/PASEP E DATA DE ADMISSAO.
-- SO PODEM SER PREENCHIDOS PARA O VINCULO CLT. PIS/PASEP NAO PODE REPETIR.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'CTPS_NUMERO') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [CTPS_NUMERO] NVARCHAR(20) NULL;
IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'CTPS_SERIE') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [CTPS_SERIE] NVARCHAR(10) NULL;
IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'CTPS_UF') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [CTPS_UF] CHAR(2) NULL;
IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'CTPS_DATA_EMISSAO') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [CTPS_DATA_EMISSAO] DATE NULL;
IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'PIS_PASEP') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [PIS_PASEP] CHAR(11) NULL;
IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'DATA_ADMISSAO') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [DATA_ADMISSAO] DATE NULL;
GO

IF NOT EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_COLABORADOR_DADOS_CLT')
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD CONSTRAINT CK_COLABORADOR_DADOS_CLT CHECK (
        [TIPO_VINCULO] = 'CLT'
        OR ([CTPS_NUMERO] IS NULL AND [CTPS_SERIE] IS NULL AND [CTPS_UF] IS NULL AND [CTPS_DATA_EMISSAO] IS NULL
            AND [PIS_PASEP] IS NULL AND [DATA_ADMISSAO] IS NULL));
GO

IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE NAME = 'UX_COLABORADOR_PRESTADOR_PIS' AND OBJECT_ID = OBJECT_ID('DBO.COLABORADOR_PRESTADOR'))
    CREATE UNIQUE INDEX UX_COLABORADOR_PRESTADOR_PIS ON DBO.COLABORADOR_PRESTADOR ([PIS_PASEP]) WHERE [PIS_PASEP] IS NOT NULL;
GO

SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'COLABORADOR_PRESTADOR'
  AND COLUMN_NAME IN ('CTPS_NUMERO', 'CTPS_SERIE', 'CTPS_UF', 'CTPS_DATA_EMISSAO', 'PIS_PASEP', 'DATA_ADMISSAO')
ORDER BY COLUMN_NAME;
GO
