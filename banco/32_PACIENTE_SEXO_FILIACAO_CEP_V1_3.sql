-- =====================================================================
-- SCRIPT 32 - PACIENTE: SEXO, FILIACAO (MAE E PAI), PAIS, CEP E BAIRRO (V1.3)
-- TABELA: PACIENTE
-- SEXO: OPCIONAL (M, F OU O).
-- NOME_MAE: OBRIGATORIO PELA TELA/API, EXCETO QUANDO MAE_NAO_POSSUI = 1 (DOCUMENTO SEM REGISTRO DA MAE).
-- NOME_PAI: OPCIONAL.
-- PAIS: PADRAO 'BRASIL' APENAS PARA AS LINHAS EXISTENTES (A TELA NAO PREENCHE SOZINHA).
-- CEP (8 DIGITOS) E BAIRRO: OBRIGATORIOS PELA TELA/API; NO BANCO FICAM NULOS NAS LINHAS EXISTENTES.
-- LINHAS EXISTENTES (DADOS DE TESTE) FICAM SEM MAE, CEP E BAIRRO; A TELA PEDE ESSES DADOS NO PROXIMO SALVAMENTO.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.PACIENTE', 'SEXO') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [SEXO] CHAR(1) NULL;
IF COL_LENGTH('DBO.PACIENTE', 'NOME_MAE') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [NOME_MAE] NVARCHAR(150) NULL;
IF COL_LENGTH('DBO.PACIENTE', 'MAE_NAO_POSSUI') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [MAE_NAO_POSSUI] BIT NOT NULL CONSTRAINT DF_PACIENTE_MAE_NAO_POSSUI DEFAULT 0;
IF COL_LENGTH('DBO.PACIENTE', 'NOME_PAI') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [NOME_PAI] NVARCHAR(150) NULL;
IF COL_LENGTH('DBO.PACIENTE', 'PAIS') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [PAIS] NVARCHAR(60) NOT NULL CONSTRAINT DF_PACIENTE_PAIS DEFAULT 'Brasil';
IF COL_LENGTH('DBO.PACIENTE', 'CEP') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [CEP] CHAR(8) NULL;
IF COL_LENGTH('DBO.PACIENTE', 'BAIRRO') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [BAIRRO] NVARCHAR(80) NULL;
GO

IF NOT EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_PACIENTE_SEXO')
    ALTER TABLE DBO.PACIENTE ADD CONSTRAINT CK_PACIENTE_SEXO CHECK (SEXO IS NULL OR SEXO IN ('M', 'F', 'O'));
IF NOT EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_PACIENTE_CEP')
    ALTER TABLE DBO.PACIENTE ADD CONSTRAINT CK_PACIENTE_CEP CHECK (CEP IS NULL OR (LEN(CEP) = 8 AND CEP NOT LIKE '%[^0-9]%'));
IF NOT EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_PACIENTE_MAE')
    ALTER TABLE DBO.PACIENTE ADD CONSTRAINT CK_PACIENTE_MAE CHECK (MAE_NAO_POSSUI = 0 OR NOME_MAE IS NULL);
GO

-- CONFERENCIA
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'PACIENTE'
  AND COLUMN_NAME IN ('SEXO', 'NOME_MAE', 'MAE_NAO_POSSUI', 'NOME_PAI', 'PAIS', 'CEP', 'BAIRRO')
ORDER BY COLUMN_NAME;
GO
