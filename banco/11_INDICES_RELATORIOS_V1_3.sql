/* VIVER BEM SAUDE - SCRIPT 11 - INDICES PARA DASHBOARDS, RELATORIOS E AUDITORIA (BLOCO 7 DA API)
   EXECUTAR DEPOIS DOS SCRIPTS 01 E 02, NO BANCO VBSAGENDA. PODE SER EXECUTADO MAIS DE UMA VEZ: CADA INDICE SO E CRIADO SE NAO EXISTIR.
   O BLOCO 7 SO LE DADOS (E GRAVA O LOG DE CONSULTA E EXPORTACAO, QUE JA EXISTE EM LOG_AUDITORIA, COM A ACAO EXPORTAR). NAO HA TABELA NOVA.

   COM POUCOS DADOS (AMBIENTE LOCAL COM PACIENTES FICTICIOS) OS INDICES NAO FAZEM DIFERENCA; ELES EVITAM LENTIDAO NO FUTURO. */

/* PAINEL DO DIA E RELATORIOS POR PERIODO (RF15 A RF22) */
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_CONSULTA_DATA' AND [OBJECT_ID] = OBJECT_ID('DBO.CONSULTA'))
    CREATE INDEX IX_CONSULTA_DATA ON DBO.[CONSULTA] ([DATA_INICIO]) INCLUDE ([STATUS], [CODIGO_PROFISSIONAL], [CODIGO_UNIDADE], [ENCAIXE], [TIPO_ATENDIMENTO], [CODIGO_CONVENIO], [VALOR]);
GO

/* FILTRO POR UNIDADE */
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_CONSULTA_UNIDADE_DATA' AND [OBJECT_ID] = OBJECT_ID('DBO.CONSULTA'))
    CREATE INDEX IX_CONSULTA_UNIDADE_DATA ON DBO.[CONSULTA] ([CODIGO_UNIDADE], [DATA_INICIO]) INCLUDE ([STATUS], [CODIGO_PROFISSIONAL], [CODIGO_CONVENIO], [TIPO_ATENDIMENTO], [VALOR]);
GO

/* FATURAMENTO POR CONVENIO (RF20) */
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_CONSULTA_CONVENIO_DATA' AND [OBJECT_ID] = OBJECT_ID('DBO.CONSULTA'))
    CREATE INDEX IX_CONSULTA_CONVENIO_DATA ON DBO.[CONSULTA] ([CODIGO_CONVENIO], [DATA_INICIO]) INCLUDE ([STATUS], [VALOR]) WHERE [CODIGO_CONVENIO] IS NOT NULL;
GO

/* CONSULTA DO LOG POR PERIODO (RNF05) */
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_LOG_AUDITORIA_DATA' AND [OBJECT_ID] = OBJECT_ID('DBO.LOG_AUDITORIA'))
    CREATE INDEX IX_LOG_AUDITORIA_DATA ON DBO.[LOG_AUDITORIA] ([DATA_HORA]) INCLUDE ([ACAO], [ENTIDADE], [CODIGO_USUARIO], [CODIGO_PACIENTE]);
GO

/* RELATORIO DE PRONTUARIOS POR PERIODO (RF25) */
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_REGISTRO_PRONTUARIO_DATA' AND [OBJECT_ID] = OBJECT_ID('DBO.REGISTRO_PRONTUARIO'))
    CREATE INDEX IX_REGISTRO_PRONTUARIO_DATA ON DBO.[REGISTRO_PRONTUARIO] ([DATA_HORA_REGS]) INCLUDE ([CODIGO_PACIENTE], [CODIGO_PROFISSIONAL]);
GO

/* RELATORIO DE PRONTUARIOS POR PROFISSIONAL (RF25) */
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_REGISTRO_PRONTUARIO_PROFISSIONAL' AND [OBJECT_ID] = OBJECT_ID('DBO.REGISTRO_PRONTUARIO'))
    CREATE INDEX IX_REGISTRO_PRONTUARIO_PROFISSIONAL ON DBO.[REGISTRO_PRONTUARIO] ([CODIGO_PROFISSIONAL], [DATA_HORA_REGS]);
GO

/* CONFERENCIA: DEVE LISTAR OS 6 INDICES. */
SELECT [NAME] AS [INDICE], OBJECT_NAME([OBJECT_ID]) AS [TABELA] FROM SYS.INDEXES
WHERE [NAME] IN ('IX_CONSULTA_DATA', 'IX_CONSULTA_UNIDADE_DATA', 'IX_CONSULTA_CONVENIO_DATA', 'IX_LOG_AUDITORIA_DATA', 'IX_REGISTRO_PRONTUARIO_DATA', 'IX_REGISTRO_PRONTUARIO_PROFISSIONAL')
ORDER BY [NAME];
GO

