USE VBSAGENDA;
GO

IF OBJECT_ID('DBO.DOCUMENTO_INTERNO') IS NULL
CREATE TABLE DBO.[DOCUMENTO_INTERNO] (
    [CODIGO_DOCUMENTO_INTERNO] INT IDENTITY(1,1) NOT NULL,
    [CODIGO_PUBLIC] UNIQUEIDENTIFIER NOT NULL,
    [TIPO_DOCUMENTO] VARCHAR(20) NOT NULL,
    [TITULO] NVARCHAR(150) NOT NULL,
    [DESCRICAO] NVARCHAR(300) NULL,
    [NOME_ARQUIVO] NVARCHAR(255) NOT NULL,
    [TIPO_CONTEUDO] VARCHAR(100) NOT NULL,
    [TAMANHO_BYTES] INT NOT NULL,
    [HASH_SHA256] CHAR(64) NOT NULL,
    [CONTEUDO] VARBINARY(MAX) NOT NULL,
    [CODIGO_USUARIO] INT NOT NULL,
    [DATA_HORA] DATETIME2(0) NOT NULL CONSTRAINT DF_DOCUMENTO_INTERNO_DATA_HORA DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_DOCUMENTO_INTERNO PRIMARY KEY ([CODIGO_DOCUMENTO_INTERNO]),
    CONSTRAINT UQ_DOCUMENTO_INTERNO_CODIGO_PUBLIC UNIQUE ([CODIGO_PUBLIC]),
    CONSTRAINT CK_DOCUMENTO_INTERNO_TIPO CHECK ([TIPO_DOCUMENTO] IN ('FOLHA_TIMBRADA','TERMO','CONTRATO','POLITICA','FORMULARIO','MODELO','OUTRO')),
    CONSTRAINT CK_DOCUMENTO_INTERNO_TAMANHO CHECK ([TAMANHO_BYTES] BETWEEN 1 AND 10485760),
    CONSTRAINT FK_DOCUMENTO_INTERNO_CODIGO_USUARIO FOREIGN KEY ([CODIGO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO])
);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE NAME = 'IX_DOCUMENTO_INTERNO_TIPO' AND OBJECT_ID = OBJECT_ID('DBO.DOCUMENTO_INTERNO'))
    CREATE INDEX IX_DOCUMENTO_INTERNO_TIPO ON DBO.[DOCUMENTO_INTERNO] ([TIPO_DOCUMENTO], [DATA_HORA] DESC);
GO

GRANT SELECT, INSERT, DELETE ON DBO.[DOCUMENTO_INTERNO] TO ROLE_APP_AGENDAMENTO;
GRANT SELECT ON DBO.[DOCUMENTO_INTERNO] TO ROLE_DBA_CORRECAO;
GO

