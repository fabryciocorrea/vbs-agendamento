   NENHUM REGISTRO E INCLUIDO OU ALTERADO SEM A SOLICITACAO DO PROFISSIONAL E O OK DO RESPONSAVEL LEGAL. TODA INCLUSAO OU
   EDICAO, PELO SISTEMA OU DIRETO NO BANCO, GRAVA: QUEM SOLICITOU, QUEM AUTORIZOU, A OBSERVACAO DA AUTORIZACAO,
   O USUARIO, O PACIENTE, A DATA E A HORA E A QUANTIDADE DE REGISTROS NO LOG_AUDITORIA.
   A EDICAO PRESERVA O TEXTO ANTERIOR EM PRONTUARIO_CORRECAO (NADA SE PERDE). O DELETE CONTINUA BLOQUEADO PARA TODOS.

   CODIGOS DE ERRO (50001 A 50042 JA EXISTEM):
