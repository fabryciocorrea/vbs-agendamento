/* ================== 2. GATILHO DE CORRECAO (SUBSTITUI O DO SCRIPT 02) ==================
   O GATILHO CONTINUA BLOQUEANDO TUDO QUE NAO FOR A COLUNA OBSERVACAO E EXIGE, EM QUALQUER ORIGEM:
   MOTIVO (OBSERVACAO DA AUTORIZACAO), AUTORIZADO_POR E SOLICITADO_POR NA SESSAO.
   - ORIGEM SISTEMA: A PROCEDURE USP_PRONTUARIO_EDITAR_ADMIN INFORMA TAMBEM CODIGO_USUARIO (E IP).
   - ORIGEM BANCO (DEFAULT): O DBA INFORMA OS TRES VALORES NA SESSAO (VER PROCEDIMENTO ABAIXO).
   A CONTA DA APLICACAO CONTINUA SEM PERMISSAO DE UPDATE NA TABELA: SO A PROCEDURE (EXECUTE AS OWNER) ALTERA.

   PROCEDIMENTO DO DBA (CORRECAO DIRETA NO BANCO, SOMENTE COM SOLICITACAO DO PROFISSIONAL E OK DO RESPONSAVEL LEGAL):
     1. ABRIR A CONEXAO COM COLUMN ENCRYPTION SETTING=ENABLED E ACESSO A CHAVE DO ALWAYS ENCRYPTED.
     2. EXEC SP_SET_SESSION_CONTEXT @KEY = N'MOTIVO',         @VALUE = N'<OBSERVACAO DA AUTORIZACAO>';
        EXEC SP_SET_SESSION_CONTEXT @KEY = N'AUTORIZADO_POR', @VALUE = N'<NOME DO RESPONSAVEL LEGAL>';
        EXEC SP_SET_SESSION_CONTEXT @KEY = N'SOLICITADO_POR', @VALUE = N'<NOME DO PROFISSIONAL QUE SOLICITOU>';
     3. UPDATE DBO.REGISTRO_PRONTUARIO SET OBSERVACAO = @NOVO_TEXTO WHERE CODIGO_REGS_PRNT = @ID;   -- PARAMETRIZADO
     4. CONFERIR A LINHA CRIADA EM DBO.PRONTUARIO_CORRECAO E O EVENTO EM DBO.LOG_AUDITORIA. */
CREATE OR ALTER TRIGGER DBO.TRG_REGISTRO_PRONTUARIO_CORRECAO ON DBO.[REGISTRO_PRONTUARIO] AFTER UPDATE AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @MOTIVO NVARCHAR(1000) = CONVERT(NVARCHAR(1000), SESSION_CONTEXT(N'MOTIVO'));
    DECLARE @AUT    NVARCHAR(150)  = CONVERT(NVARCHAR(150),  SESSION_CONTEXT(N'AUTORIZADO_POR'));
    DECLARE @SOL    NVARCHAR(150)  = CONVERT(NVARCHAR(150),  SESSION_CONTEXT(N'SOLICITADO_POR'));
    DECLARE @ORIGEM NVARCHAR(10)   = ISNULL(CONVERT(NVARCHAR(10), SESSION_CONTEXT(N'ORIGEM')), N'BANCO');
    DECLARE @USU    INT            = TRY_CONVERT(INT, SESSION_CONTEXT(N'CODIGO_USUARIO'));
    DECLARE @IP     NVARCHAR(45)   = CONVERT(NVARCHAR(45), SESSION_CONTEXT(N'IP'));
    DECLARE @QTD    INT            = (SELECT COUNT(*) FROM INSERTED);

    IF IS_MEMBER('ROLE_APP_AGENDAMENTO') = 1
       OR UPDATE([CODIGO_REGS_PRNT]) OR UPDATE([CODIGO_PUBLIC]) OR UPDATE([CODIGO_PACIENTE]) OR UPDATE([CODIGO_CONSULTA]) OR UPDATE([CODIGO_PROFISSIONAL])
       OR UPDATE([NOME_PROFISSIONAL]) OR UPDATE([REGISTRO_PROFISSIONAL]) OR UPDATE([NUMERO_CONSELHO]) OR UPDATE([UF_CONSELHO]) OR UPDATE([DATA_HORA_REGS])
       OR UPDATE([CODIGO_USUARIO_INCLUSAO]) OR UPDATE([SOLICITADO_POR]) OR UPDATE([AUTORIZADO_POR]) OR UPDATE([OBS_AUTORIZACAO])
       OR NULLIF(LTRIM(RTRIM(@MOTIVO)), '') IS NULL OR NULLIF(LTRIM(RTRIM(@AUT)), '') IS NULL OR NULLIF(LTRIM(RTRIM(@SOL)), '') IS NULL
       OR @ORIGEM NOT IN (N'SISTEMA', N'BANCO') OR (@ORIGEM = N'SISTEMA' AND @USU IS NULL)
    BEGIN
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW 50031, 'Registro do prontuário imutável (RN19). A edição exige a solicitação do profissional e o OK do responsável legal, informados com a observação da autorização; só o administrador (pelo sistema) ou o DBA (pelo banco) altera, apenas a coluna OBSERVACAO.', 1;
    END;

    INSERT INTO DBO.[PRONTUARIO_CORRECAO] ([CODIGO_REGS_PRNT], [OBSERVACAO_ANTERIOR], [OBSERVACAO_NOVO], [MOTIVO], [AUTORIZADO_USUARIO], [CORRECAO_USUARIO], [ORIGEM], [CODIGO_USUARIO], [SOLICITADO_POR])
    SELECT I.[CODIGO_REGS_PRNT], D.[OBSERVACAO], I.[OBSERVACAO], @MOTIVO, @AUT, ORIGINAL_LOGIN(), @ORIGEM, CASE WHEN @ORIGEM = N'SISTEMA' THEN @USU END, @SOL
    FROM INSERTED AS I JOIN DELETED AS D ON D.[CODIGO_REGS_PRNT] = I.[CODIGO_REGS_PRNT];

    /* LOG: QUEM (USUARIO), O PACIENTE, QUEM SOLICITOU, QUEM AUTORIZOU, A OBSERVACAO E A QUANTIDADE DE REGISTROS. DATA E HORA = DATA_HORA DO LOG (UTC). */
    INSERT INTO DBO.[LOG_AUDITORIA] ([CODIGO_USUARIO], [ACAO], [ENTIDADE], [CODIGO_ENTIDADE], [CODIGO_PACIENTE], [DETALHES], [IP])
    SELECT CASE WHEN @ORIGEM = N'SISTEMA' THEN @USU END,
           CASE WHEN @ORIGEM = N'SISTEMA' THEN 'EDITAR' ELSE 'CORRECAO_PRONTUARIO' END,
           'REGISTRO_PRONTUARIO', I.[CODIGO_REGS_PRNT], I.[CODIGO_PACIENTE],
           CONCAT(N'Edição de registro do prontuário ', CASE WHEN @ORIGEM = N'SISTEMA' THEN N'pelo sistema' ELSE N'direto no banco' END,
                  N'. Usuário: ', COALESCE((SELECT U.[NOME_COMPLETO] FROM DBO.[USUARIO] AS U WHERE U.[CODIGO_USUARIO] = @USU), ORIGINAL_LOGIN()),
                  N'. Paciente: ', (SELECT P.[NOME] FROM DBO.[PACIENTE] AS P WHERE P.[CODIGO_PACIENTE] = I.[CODIGO_PACIENTE]),
                  N'. Registros alterados: ', @QTD,
                  N'. Solicitado por: ', @SOL, N'. Autorizado por: ', @AUT, N'. Observação da autorização: ', @MOTIVO),
           @IP
    FROM INSERTED AS I;
END;
GO

/* ================== 3. EDICAO PELO ADMINISTRADOR (SISTEMA) ================== */
CREATE OR ALTER PROCEDURE DBO.USP_PRONTUARIO_EDITAR_ADMIN
    @CODIGO_USUARIO INT, @CODIGO_PUBLIC_PACIENTE UNIQUEIDENTIFIER, @CODIGO_PUBLIC_REGISTRO UNIQUEIDENTIFIER,
    @OBSERVACAO NVARCHAR(MAX), @SOLICITADO_POR NVARCHAR(150), @AUTORIZADO_POR NVARCHAR(150), @OBS_AUTORIZACAO NVARCHAR(1000), @IP NVARCHAR(45) = NULL
WITH EXECUTE AS OWNER
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NOT EXISTS (SELECT 1 FROM DBO.[USUARIO] AS U JOIN DBO.[PERFIL_ACESSO] AS P ON P.[CODIGO_PERFIL] = U.[CODIGO_PERFIL]
                   WHERE U.[CODIGO_USUARIO] = @CODIGO_USUARIO AND U.[ATIVO] = 1 AND P.[PROTEGIDO] = 1)
        THROW 50060, 'Somente o administrador ativo pode editar o prontuário.', 1;

    IF NULLIF(LTRIM(RTRIM(@SOLICITADO_POR)), '') IS NULL OR NULLIF(LTRIM(RTRIM(@AUTORIZADO_POR)), '') IS NULL
       OR LEN(LTRIM(RTRIM(ISNULL(@OBS_AUTORIZACAO, N'')))) < 10
        THROW 50062, 'Informe quem solicitou, quem autorizou e a observação da autorização (mínimo de 10 caracteres).', 1;

    DECLARE @PACIENTE INT = (SELECT [CODIGO_PACIENTE] FROM DBO.[PACIENTE] WHERE [CODIGO_PUBLIC] = @CODIGO_PUBLIC_PACIENTE);
    DECLARE @REGISTRO BIGINT = (SELECT [CODIGO_REGS_PRNT] FROM DBO.[REGISTRO_PRONTUARIO]
                                WHERE [CODIGO_PUBLIC] = @CODIGO_PUBLIC_REGISTRO AND [CODIGO_PACIENTE] = @PACIENTE);
    IF @PACIENTE IS NULL OR @REGISTRO IS NULL
        THROW 50061, 'Registro não encontrado para este paciente.', 1;

    /* DADOS PARA O GATILHO (VALEM SO PARA ESTA SESSAO E SAO LIMPOS NO FIM). */
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'ORIGEM',         @VALUE = N'SISTEMA';
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'CODIGO_USUARIO', @VALUE = @CODIGO_USUARIO;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'MOTIVO',         @VALUE = @OBS_AUTORIZACAO;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'AUTORIZADO_POR', @VALUE = @AUTORIZADO_POR;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'SOLICITADO_POR', @VALUE = @SOLICITADO_POR;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'IP',             @VALUE = @IP;

    BEGIN TRY
        UPDATE DBO.[REGISTRO_PRONTUARIO] SET [OBSERVACAO] = @OBSERVACAO WHERE [CODIGO_REGS_PRNT] = @REGISTRO;
    END TRY
    BEGIN CATCH
        EXEC SP_SET_SESSION_CONTEXT @KEY = N'ORIGEM', @VALUE = NULL;
        EXEC SP_SET_SESSION_CONTEXT @KEY = N'MOTIVO', @VALUE = NULL;
        THROW;
    END CATCH;

    EXEC SP_SET_SESSION_CONTEXT @KEY = N'ORIGEM',         @VALUE = NULL;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'CODIGO_USUARIO', @VALUE = NULL;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'MOTIVO',         @VALUE = NULL;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'AUTORIZADO_POR', @VALUE = NULL;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'SOLICITADO_POR', @VALUE = NULL;
    EXEC SP_SET_SESSION_CONTEXT @KEY = N'IP',             @VALUE = NULL;
END;
GO

/* ================== 4. INCLUSAO PELO ADMINISTRADOR (SISTEMA) ==================
   O REGISTRO FICA EM NOME DO PROFISSIONAL QUE SOLICITOU (NOME E CONSELHO COPIADOS DO CADASTRO, RN19) E MARCA O ADMINISTRADOR
   QUE DIGITOU. A INCLUSAO FEITA PELO PROPRIO PROFISSIONAL RESPONSAVEL CONTINUA SENDO UM INSERT SIMPLES DA APLICACAO. */
CREATE OR ALTER PROCEDURE DBO.USP_PRONTUARIO_INCLUIR_ADMIN
    @CODIGO_USUARIO INT, @CODIGO_PUBLIC_PACIENTE UNIQUEIDENTIFIER, @CODIGO_PROFISSIONAL INT, @CODIGO_PUBLIC_CONSULTA UNIQUEIDENTIFIER = NULL,
    @OBSERVACAO NVARCHAR(MAX), @SOLICITADO_POR NVARCHAR(150), @AUTORIZADO_POR NVARCHAR(150), @OBS_AUTORIZACAO NVARCHAR(1000), @IP NVARCHAR(45) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NOT EXISTS (SELECT 1 FROM DBO.[USUARIO] AS U JOIN DBO.[PERFIL_ACESSO] AS P ON P.[CODIGO_PERFIL] = U.[CODIGO_PERFIL]
                   WHERE U.[CODIGO_USUARIO] = @CODIGO_USUARIO AND U.[ATIVO] = 1 AND P.[PROTEGIDO] = 1)
        THROW 50060, 'Somente o administrador ativo pode incluir registro em nome de um profissional.', 1;

    IF NULLIF(LTRIM(RTRIM(@SOLICITADO_POR)), '') IS NULL OR NULLIF(LTRIM(RTRIM(@AUTORIZADO_POR)), '') IS NULL
       OR LEN(LTRIM(RTRIM(ISNULL(@OBS_AUTORIZACAO, N'')))) < 10
        THROW 50062, 'Informe quem solicitou, quem autorizou e a observação da autorização (mínimo de 10 caracteres).', 1;

    DECLARE @PACIENTE INT, @ATIVO BIT;
    SELECT @PACIENTE = [CODIGO_PACIENTE], @ATIVO = [ATIVO] FROM DBO.[PACIENTE] WHERE [CODIGO_PUBLIC] = @CODIGO_PUBLIC_PACIENTE;
    IF @PACIENTE IS NULL OR @ATIVO = 0
        THROW 50063, 'Paciente inexistente ou inativo.', 1;

    DECLARE @NOME NVARCHAR(150), @REG NVARCHAR(10), @NUM NVARCHAR(20), @UF CHAR(2);
    SELECT @NOME = [NOME], @REG = [REGISTRO_PROFISSIONAL], @NUM = [NUMERO_CONSELHO], @UF = [UF_CONSELHO]
    FROM DBO.[PROFISSIONAL] WHERE [CODIGO_PROFISSIONAL] = @CODIGO_PROFISSIONAL AND [ATIVO] = 1;
    IF @NOME IS NULL
        THROW 50064, 'Profissional inexistente ou inativo.', 1;

    DECLARE @CONSULTA INT = NULL;
    IF @CODIGO_PUBLIC_CONSULTA IS NOT NULL
    BEGIN
        SELECT @CONSULTA = [CODIGO_CONSULTA] FROM DBO.[CONSULTA]
        WHERE [CODIGO_PUBLIC] = @CODIGO_PUBLIC_CONSULTA AND [CODIGO_PACIENTE] = @PACIENTE AND [CODIGO_PROFISSIONAL] = @CODIGO_PROFISSIONAL;
        IF @CONSULTA IS NULL
            THROW 50065, 'A consulta informada não pertence a este paciente e a este profissional.', 1;
    END;

    DECLARE @NOVO TABLE ([CODIGO_REGS_PRNT] BIGINT, [CODIGO_PUBLIC] UNIQUEIDENTIFIER);
    DECLARE @NOME_PACIENTE NVARCHAR(150) = (SELECT [NOME] FROM DBO.[PACIENTE] WHERE [CODIGO_PACIENTE] = @PACIENTE);
    DECLARE @NOME_USUARIO  NVARCHAR(150) = (SELECT [NOME_COMPLETO] FROM DBO.[USUARIO] WHERE [CODIGO_USUARIO] = @CODIGO_USUARIO);

    BEGIN TRANSACTION;
        INSERT INTO DBO.[REGISTRO_PRONTUARIO] ([CODIGO_PACIENTE], [CODIGO_CONSULTA], [CODIGO_PROFISSIONAL], [NOME_PROFISSIONAL], [REGISTRO_PROFISSIONAL], [NUMERO_CONSELHO], [UF_CONSELHO],
                                              [OBSERVACAO], [CODIGO_USUARIO_INCLUSAO], [SOLICITADO_POR], [AUTORIZADO_POR], [OBS_AUTORIZACAO])
        OUTPUT INSERTED.[CODIGO_REGS_PRNT], INSERTED.[CODIGO_PUBLIC] INTO @NOVO
        VALUES (@PACIENTE, @CONSULTA, @CODIGO_PROFISSIONAL, @NOME, @REG, @NUM, @UF,
                @OBSERVACAO, @CODIGO_USUARIO, LTRIM(RTRIM(@SOLICITADO_POR)), LTRIM(RTRIM(@AUTORIZADO_POR)), LTRIM(RTRIM(@OBS_AUTORIZACAO)));

        INSERT INTO DBO.[LOG_AUDITORIA] ([CODIGO_USUARIO], [ACAO], [ENTIDADE], [CODIGO_ENTIDADE], [CODIGO_PACIENTE], [DETALHES], [IP])
        SELECT @CODIGO_USUARIO, 'INCLUIR', 'REGISTRO_PRONTUARIO', N.[CODIGO_REGS_PRNT], @PACIENTE,
               CONCAT(N'Inclusão de registro no prontuário pelo sistema. Usuário: ', @NOME_USUARIO, N'. Paciente: ', @NOME_PACIENTE,
                      N'. Registros incluídos: 1. Em nome do profissional: ', @NOME,
                      N'. Solicitado por: ', LTRIM(RTRIM(@SOLICITADO_POR)), N'. Autorizado por: ', LTRIM(RTRIM(@AUTORIZADO_POR)),
                      N'. Observação da autorização: ', LTRIM(RTRIM(@OBS_AUTORIZACAO))), @IP
        FROM @NOVO AS N;
    COMMIT TRANSACTION;

    SELECT [CODIGO_PUBLIC] FROM @NOVO;
END;
GO

/* ================== 5. PERMISSOES ================== */
GRANT EXECUTE ON DBO.USP_PRONTUARIO_EDITAR_ADMIN  TO ROLE_APP_AGENDAMENTO;
GRANT EXECUTE ON DBO.USP_PRONTUARIO_INCLUIR_ADMIN TO ROLE_APP_AGENDAMENTO;
GO

