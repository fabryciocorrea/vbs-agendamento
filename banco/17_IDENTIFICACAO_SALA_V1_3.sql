-- SCRIPT 17 - IDENTIFICACAO DA SALA AMPLIADA (V1.3)
-- O CAMPO SALA.NUMERO PASSA DE 10 PARA 40 CARACTERES PARA ACEITAR
-- "SALA 312", "CONSULTORIO 01" ETC. MANTEM A UNICIDADE POR UNIDADE.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF EXISTS (SELECT 1 FROM SYS.COLUMNS
           WHERE OBJECT_ID = OBJECT_ID('DBO.SALA') AND NAME = 'NUMERO' AND MAX_LENGTH < 80)
BEGIN
    ALTER TABLE DBO.SALA ALTER COLUMN [NUMERO] NVARCHAR(40) NOT NULL;
END
GO

SELECT NAME, TYPE_NAME(SYSTEM_TYPE_ID) AS TIPO, MAX_LENGTH / 2 AS CARACTERES, IS_NULLABLE
FROM SYS.COLUMNS WHERE OBJECT_ID = OBJECT_ID('DBO.SALA') AND NAME = 'NUMERO';
GO
