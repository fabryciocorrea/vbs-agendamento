-- =====================================================================
-- SCRIPT 37 - PACOTES DE CONSULTAS PARTICULARES (V1.3)
-- EXECUTAR DEPOIS DOS SCRIPTS 01 A 36, NO BANCO VBSAGENDA. PODE SER EXECUTADO MAIS DE UMA VEZ.
-- 1) TABELA PACOTE: MODELO DO PACOTE (NOME, ESPECIALIDADE, QUANTIDADE DE SESSOES, VALOR TOTAL, VALIDADE EM DIAS).
-- 2) TABELA PACOTE_PACIENTE: PACOTE VENDIDO A UM PACIENTE. GUARDA UMA COPIA DAS CONDICOES NA HORA DA VENDA (MUDAR O MODELO
--    DEPOIS NAO ALTERA O QUE O PACIENTE JA COMPROU), A FORMA DE PAGAMENTO E SE O PAGAMENTO FOI RECEBIDO.
-- 3) COLUNA CONSULTA.CODIGO_PACOTE_PACIENTE: LIGA A CONSULTA PARTICULAR AO PACOTE QUE ELA CONSUMIU.
--    AS SESSOES USADAS NAO SAO GUARDADAS: SAO CONTADAS PELAS CONSULTAS LIGADAS AO PACOTE QUE NAO ESTAO CANCELADAS NEM REMARCADAS.
--    ASSIM, CANCELAR UMA CONSULTA DEVOLVE A SESSAO SOZINHO, E A FALTA CONSOME A SESSAO.
-- 4) AS TELAS DE PERMISSAO "PACOTE.CADASTRO" E "PACOTE.VENDA" SAO CRIADAS PELO SERVIDOR AO INICIAR; LIBERE EM PERFIS DE ACESSO.
-- =====================================================================
USE VBSAGENDA;
GO

IF OBJECT_ID('DBO.PACOTE') IS NULL
CREATE TABLE DBO.[PACOTE] (
    [CODIGO_PACOTE] INT IDENTITY(1,1) NOT NULL,
    [NOME] NVARCHAR(100) NOT NULL,
    [CODIGO_ESPECIALIDADE] INT NOT NULL,
    [QUANTIDADE_SESSOES] INT NOT NULL,
    [VALOR] DECIMAL(10,2) NOT NULL,
    [VALIDADE_DIAS] INT NOT NULL,
    [ATIVO] BIT NOT NULL CONSTRAINT DF_PACOTE_ATIVO DEFAULT 1,
    [DATA_CRIACAO] DATETIME2(0) NOT NULL CONSTRAINT DF_PACOTE_DATA_CRIACAO DEFAULT SYSUTCDATETIME(),
    [CRIACAO_USUARIO] INT NULL,
    [DATA_ATUALIZACAO] DATETIME2(0) NOT NULL CONSTRAINT DF_PACOTE_DATA_ATUALIZACAO DEFAULT SYSUTCDATETIME(),
    [ATUALIZACAO_USUARIO] INT NULL,
    CONSTRAINT PK_PACOTE PRIMARY KEY ([CODIGO_PACOTE]),
    CONSTRAINT UQ_PACOTE_NOME UNIQUE ([NOME]),
    CONSTRAINT CK_PACOTE_QUANTIDADE CHECK ([QUANTIDADE_SESSOES] BETWEEN 1 AND 60),
    CONSTRAINT CK_PACOTE_VALOR CHECK ([VALOR] >= 0 AND [VALOR] < 100000000),
    CONSTRAINT CK_PACOTE_VALIDADE CHECK ([VALIDADE_DIAS] BETWEEN 1 AND 365),
    CONSTRAINT FK_PACOTE_CODIGO_ESPECIALIDADE FOREIGN KEY ([CODIGO_ESPECIALIDADE]) REFERENCES DBO.[ESPECIALIDADE] ([CODIGO_ESPECIALIDADE]),
    CONSTRAINT FK_PACOTE_CRIACAO_USUARIO FOREIGN KEY ([CRIACAO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO]),
    CONSTRAINT FK_PACOTE_ATUALIZACAO_USUARIO FOREIGN KEY ([ATUALIZACAO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO])
);
GO

IF OBJECT_ID('DBO.PACOTE_PACIENTE') IS NULL
CREATE TABLE DBO.[PACOTE_PACIENTE] (
    [CODIGO_PACOTE_PACIENTE] INT IDENTITY(1,1) NOT NULL,
    [CODIGO_PUBLIC] UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_PACOTE_PACIENTE_CODIGO_PUBLIC DEFAULT NEWID(),
    [CODIGO_PACOTE] INT NOT NULL,
    [CODIGO_PACIENTE] INT NOT NULL,
    [NOME] NVARCHAR(100) NOT NULL,
    [CODIGO_ESPECIALIDADE] INT NOT NULL,
    [QUANTIDADE_SESSOES] INT NOT NULL,
    [VALOR] DECIMAL(10,2) NOT NULL,
    [VALOR_SESSAO] DECIMAL(10,2) NOT NULL,
    [DATA_INICIO] DATE NOT NULL,
    [DATA_VALIDADE] DATE NOT NULL,
    [CODIGO_PAGAMENTO] INT NOT NULL,
    [PAGAMENTO_CONFIRMADO] BIT NOT NULL CONSTRAINT DF_PACOTE_PACIENTE_PAGAMENTO DEFAULT 0,
    [DATA_PAGAMENTO] DATETIME2(0) NULL,
    [PAGAMENTO_USUARIO] INT NULL,
    [STATUS] VARCHAR(10) NOT NULL CONSTRAINT DF_PACOTE_PACIENTE_STATUS DEFAULT 'ATIVO',
    [DATA_CANCELAMENTO] DATETIME2(0) NULL,
    [CANCELAMENTO_USUARIO] INT NULL,
    [MOTIVO_CANCELAMENTO] NVARCHAR(500) NULL,
    [DATA_VENDA] DATETIME2(0) NOT NULL CONSTRAINT DF_PACOTE_PACIENTE_DATA_VENDA DEFAULT SYSUTCDATETIME(),
    [VENDA_USUARIO] INT NOT NULL,
    CONSTRAINT PK_PACOTE_PACIENTE PRIMARY KEY ([CODIGO_PACOTE_PACIENTE]),
    CONSTRAINT UQ_PACOTE_PACIENTE_CODIGO_PUBLIC UNIQUE ([CODIGO_PUBLIC]),
    CONSTRAINT CK_PACOTE_PACIENTE_STATUS CHECK ([STATUS] IN ('ATIVO','CANCELADO')),
    CONSTRAINT CK_PACOTE_PACIENTE_QUANTIDADE CHECK ([QUANTIDADE_SESSOES] BETWEEN 1 AND 60),
    CONSTRAINT CK_PACOTE_PACIENTE_VALIDADE CHECK ([DATA_VALIDADE] >= [DATA_INICIO]),
    CONSTRAINT FK_PACOTE_PACIENTE_CODIGO_PACOTE FOREIGN KEY ([CODIGO_PACOTE]) REFERENCES DBO.[PACOTE] ([CODIGO_PACOTE]),
    CONSTRAINT FK_PACOTE_PACIENTE_CODIGO_PACIENTE FOREIGN KEY ([CODIGO_PACIENTE]) REFERENCES DBO.[PACIENTE] ([CODIGO_PACIENTE]),
    CONSTRAINT FK_PACOTE_PACIENTE_CODIGO_ESPECIALIDADE FOREIGN KEY ([CODIGO_ESPECIALIDADE]) REFERENCES DBO.[ESPECIALIDADE] ([CODIGO_ESPECIALIDADE]),
    CONSTRAINT FK_PACOTE_PACIENTE_CODIGO_PAGAMENTO FOREIGN KEY ([CODIGO_PAGAMENTO]) REFERENCES DBO.[FORMA_PAGAMENTO] ([CODIGO_PAGAMENTO]),
    CONSTRAINT FK_PACOTE_PACIENTE_PAGAMENTO_USUARIO FOREIGN KEY ([PAGAMENTO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO]),
    CONSTRAINT FK_PACOTE_PACIENTE_CANCELAMENTO_USUARIO FOREIGN KEY ([CANCELAMENTO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO]),
    CONSTRAINT FK_PACOTE_PACIENTE_VENDA_USUARIO FOREIGN KEY ([VENDA_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO])
);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE NAME = 'IX_PACOTE_PACIENTE_PACIENTE' AND OBJECT_ID = OBJECT_ID('DBO.PACOTE_PACIENTE'))
    CREATE INDEX IX_PACOTE_PACIENTE_PACIENTE ON DBO.[PACOTE_PACIENTE] ([CODIGO_PACIENTE], [STATUS], [DATA_VALIDADE]);
GO

-- LIGACAO DA CONSULTA COM O PACOTE.
IF COL_LENGTH('DBO.CONSULTA', 'CODIGO_PACOTE_PACIENTE') IS NULL
    ALTER TABLE DBO.[CONSULTA] ADD [CODIGO_PACOTE_PACIENTE] INT NULL;
GO

IF NOT EXISTS (SELECT 1 FROM SYS.FOREIGN_KEYS WHERE NAME = 'FK_CONSULTA_CODIGO_PACOTE_PACIENTE')
    ALTER TABLE DBO.[CONSULTA] ADD CONSTRAINT FK_CONSULTA_CODIGO_PACOTE_PACIENTE
        FOREIGN KEY ([CODIGO_PACOTE_PACIENTE]) REFERENCES DBO.[PACOTE_PACIENTE] ([CODIGO_PACOTE_PACIENTE]);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE NAME = 'IX_CONSULTA_PACOTE_PACIENTE' AND OBJECT_ID = OBJECT_ID('DBO.CONSULTA'))
    CREATE INDEX IX_CONSULTA_PACOTE_PACIENTE ON DBO.[CONSULTA] ([CODIGO_PACOTE_PACIENTE]) WHERE [CODIGO_PACOTE_PACIENTE] IS NOT NULL;
GO

GRANT SELECT, INSERT, UPDATE ON DBO.[PACOTE] TO ROLE_APP_AGENDAMENTO;
GRANT SELECT, INSERT, UPDATE ON DBO.[PACOTE_PACIENTE] TO ROLE_APP_AGENDAMENTO;
GRANT UPDATE ON DBO.[CONSULTA] ([CODIGO_PACOTE_PACIENTE]) TO ROLE_APP_AGENDAMENTO;
GRANT SELECT ON DBO.[PACOTE] TO ROLE_DBA_CORRECAO;
GRANT SELECT ON DBO.[PACOTE_PACIENTE] TO ROLE_DBA_CORRECAO;
GO

