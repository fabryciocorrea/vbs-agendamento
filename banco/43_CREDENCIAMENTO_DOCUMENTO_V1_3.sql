USE VBSAGENDA;
GO

IF OBJECT_ID('DBO.CREDENCIAMENTO_DOCUMENTO') IS NULL
CREATE TABLE DBO.[CREDENCIAMENTO_DOCUMENTO] (
    [CODIGO_CREDENCIAMENTO_DOCUMENTO] INT IDENTITY(1,1) NOT NULL,
    [CODIGO_PUBLIC] UNIQUEIDENTIFIER NOT NULL,
    [CODIGO_CREDENCIAMENTO] INT NOT NULL,
    [TIPO_DOCUMENTO] VARCHAR(20) NOT NULL,
    [DESCRICAO] NVARCHAR(150) NULL,
    [NOME_ARQUIVO] NVARCHAR(255) NOT NULL,
    [TIPO_CONTEUDO] VARCHAR(100) NOT NULL,
    [TAMANHO_BYTES] INT NOT NULL,
    [HASH_SHA256] CHAR(64) NOT NULL,
    [CONTEUDO] VARBINARY(MAX) NOT NULL,
    [CODIGO_USUARIO] INT NOT NULL,
    [DATA_HORA] DATETIME2(0) NOT NULL CONSTRAINT DF_CREDENCIAMENTO_DOCUMENTO_DATA_HORA DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_CREDENCIAMENTO_DOCUMENTO PRIMARY KEY ([CODIGO_CREDENCIAMENTO_DOCUMENTO]),
    CONSTRAINT UQ_CREDENCIAMENTO_DOCUMENTO_CODIGO_PUBLIC UNIQUE ([CODIGO_PUBLIC]),
    CONSTRAINT CK_CREDENCIAMENTO_DOCUMENTO_TIPO CHECK ([TIPO_DOCUMENTO] IN ('PROTOCOLO','CONTRATO','APROVACAO','TABELA_VALORES','COMUNICADO','OUTRO')),
    CONSTRAINT CK_CREDENCIAMENTO_DOCUMENTO_TAMANHO CHECK ([TAMANHO_BYTES] BETWEEN 1 AND 10485760),
    CONSTRAINT FK_CREDENCIAMENTO_DOCUMENTO_CREDENCIAMENTO FOREIGN KEY ([CODIGO_CREDENCIAMENTO]) REFERENCES DBO.[CREDENCIAMENTO_CONVENIO] ([CODIGO_CREDENCIAMENTO]) ON DELETE CASCADE,
    CONSTRAINT FK_CREDENCIAMENTO_DOCUMENTO_CODIGO_USUARIO FOREIGN KEY ([CODIGO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO])
);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE NAME = 'IX_CREDENCIAMENTO_DOCUMENTO_CRED' AND OBJECT_ID = OBJECT_ID('DBO.CREDENCIAMENTO_DOCUMENTO'))
    CREATE INDEX IX_CREDENCIAMENTO_DOCUMENTO_CRED ON DBO.[CREDENCIAMENTO_DOCUMENTO] ([CODIGO_CREDENCIAMENTO], [DATA_HORA] DESC);
GO

GRANT SELECT, INSERT, DELETE ON DBO.[CREDENCIAMENTO_DOCUMENTO] TO ROLE_APP_AGENDAMENTO;
GRANT SELECT ON DBO.[CREDENCIAMENTO_DOCUMENTO] TO ROLE_DBA_CORRECAO;
GO

