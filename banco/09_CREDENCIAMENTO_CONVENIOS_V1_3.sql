    ALTER TABLE DBO.[CONSULTA] ADD CONSTRAINT FK_CONSULTA_CREDENCIAMENTO_LIBERADO_POR FOREIGN KEY ([CREDENCIAMENTO_LIBERADO_POR]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO]);
GO

/* ================== 4. GATILHO NA CONSULTA (REDE DE SEGURANCA) ==================
   BARRA QUALQUER INCLUSAO OU TROCA DE CONVENIO, UNIDADE OU ESPECIALIDADE SEM CREDENCIAMENTO, SALVO CONSULTA LIBERADA PELO ADMINISTRADOR.
   MUDAR O STATUS OU O HORARIO DE UMA CONSULTA JA GRAVADA NAO REAVALIA O CREDENCIAMENTO (J4). */
CREATE OR ALTER TRIGGER DBO.TRG_CONSULTA_CREDENCIAMENTO ON DBO.[CONSULTA] AFTER INSERT, UPDATE AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (SELECT 1
               FROM INSERTED AS I LEFT JOIN DELETED AS D ON D.[CODIGO_CONSULTA] = I.[CODIGO_CONSULTA]
               WHERE I.[CODIGO_CONVENIO] IS NOT NULL
                 AND I.[STATUS] NOT IN ('CANCELADA', 'REMARCADA', 'FALTA')
                 AND I.[CREDENCIAMENTO_LIBERADO_POR] IS NULL
                 AND (D.[CODIGO_CONSULTA] IS NULL
                      OR ISNULL(D.[CODIGO_CONVENIO], 0) <> I.[CODIGO_CONVENIO]
                      OR D.[CODIGO_UNIDADE] <> I.[CODIGO_UNIDADE]
                      OR D.[CODIGO_ESPECIALIDADE] <> I.[CODIGO_ESPECIALIDADE])
                 AND DBO.FN_CREDENCIADO(I.[CODIGO_CONVENIO], I.[CODIGO_UNIDADE], I.[CODIGO_ESPECIALIDADE], CONVERT(DATE, DATEADD(HOUR, -3, I.[DATA_INICIO]))) = 0)
    BEGIN
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW 50070, 'Convênio sem credenciamento aprovado para esta unidade e especialidade na data da consulta.', 1;
    END;
END;
GO

/* ================== 5. PROCEDURES RECRIADAS (COM A CONFERENCIA E A LIBERACAO) ================== */
CREATE OR ALTER PROCEDURE DBO.USP_CONSULTA_CRIAR
    @CODIGO_PACIENTE INT, @CODIGO_PROFISSIONAL INT, @CODIGO_ESPECIALIDADE INT, @CODIGO_UNIDADE INT,
    @CODIGO_SALA INT = NULL, @MODALIDADE NVARCHAR(10), @LINK_ONLINE NVARCHAR(500) = NULL,
    @TIPO_ATENDIMENTO NVARCHAR(10), @CODIGO_CONVENIO INT = NULL, @NUMERO_CARTEIRINHA NVARCHAR(30) = NULL,
    @DATA_INICIO DATETIME2(0), @DATA_FIM DATETIME2(0) = NULL,
    @VALOR DECIMAL(10,2), @CODIGO_PAGAMENTO INT, @PAGAMENTO_CONFIRMADO BIT = 0,
    @CODIGO_CONSULTA_ORIGEM INT = NULL, @ENCAIXE BIT = 0, @CODIGO_USUARIO INT,
    @LIBERACAO_USUARIO INT = NULL, @LIBERACAO_JUSTIFICATIVA NVARCHAR(500) = NULL,
    @CODIGO_CONSULTA INT OUTPUT, @CODIGO_PUBLIC UNIQUEIDENTIFIER OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @DATA_FIM IS NULL
    BEGIN
        DECLARE @DUR INT = ISNULL(TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'DURACAO_PADRAO_CONSULTA_MIN')), 45);
        SET @DATA_FIM = DATEADD(MINUTE, @DUR, @DATA_INICIO);
    END;

    /* CREDENCIAMENTO DO CONVENIO (RN35): SEM CREDENCIAMENTO APROVADO E VIGENTE NA UNIDADE E ESPECIALIDADE, O AGENDAMENTO E BLOQUEADO.
       SO O ADMINISTRADOR LIBERA, COM JUSTIFICATIVA. A LIBERACAO FICA GRAVADA NA CONSULTA. */
    DECLARE @LIBERAR_POR INT = NULL, @LIBERAR_JUST NVARCHAR(500) = NULL;
    IF @CODIGO_CONVENIO IS NOT NULL
       AND DBO.FN_CREDENCIADO(@CODIGO_CONVENIO, @CODIGO_UNIDADE, @CODIGO_ESPECIALIDADE, CONVERT(DATE, DATEADD(HOUR, -3, @DATA_INICIO))) = 0
    BEGIN
        IF @LIBERACAO_USUARIO IS NULL
            THROW 50070, 'Convênio sem credenciamento aprovado para esta unidade e especialidade na data da consulta.', 1;
        IF NULLIF(LTRIM(RTRIM(@LIBERACAO_JUSTIFICATIVA)), '') IS NULL
            THROW 50071, 'Informe a justificativa da liberação do credenciamento.', 1;
        IF NOT EXISTS (SELECT 1 FROM DBO.[USUARIO] AS U JOIN DBO.[PERFIL_ACESSO] AS P ON P.[CODIGO_PERFIL] = U.[CODIGO_PERFIL]
                       WHERE U.[CODIGO_USUARIO] = @LIBERACAO_USUARIO AND U.[ATIVO] = 1 AND P.[PROTEGIDO] = 1)
            THROW 50072, 'Somente o administrador ativo pode liberar consulta sem credenciamento.', 1;
        SET @LIBERAR_POR = @LIBERACAO_USUARIO;
        SET @LIBERAR_JUST = LTRIM(RTRIM(@LIBERACAO_JUSTIFICATIVA));
    END;

    BEGIN TRANSACTION;

    DECLARE @RECURSO NVARCHAR(100) = N'AGENDA_PROFISSIONAL_' + CONVERT(NVARCHAR(10), @CODIGO_PROFISSIONAL);
    DECLARE @R INT;
    EXEC @R = SP_GETAPPLOCK @RESOURCE = @RECURSO, @LOCKMODE = 'EXCLUSIVE', @LOCKOWNER = 'TRANSACTION', @LOCKTIMEOUT = 10000;
    IF @R < 0 THROW 50001, 'Agenda do profissional em uso por outra operação. Tente novamente.', 1;

    IF EXISTS (SELECT 1 FROM DBO.[CONSULTA] WITH (UPDLOCK, HOLDLOCK)
               WHERE [CODIGO_PROFISSIONAL] = @CODIGO_PROFISSIONAL
                 AND [STATUS] NOT IN ('CANCELADA', 'REMARCADA')
                 AND [DATA_INICIO] < @DATA_FIM AND [DATA_FIM] > @DATA_INICIO)
        THROW 50002, 'Horário indisponível: o profissional já tem consulta nesse intervalo (RN09).', 1;

    IF @ENCAIXE = 1
    BEGIN
        /* [REVISAR] LIMITE DE ENCAIXES POR PROFISSIONAL E POR DIA (PARAMETRO LIMITE_ENCAIXES_DIA).
           SE O LIMITE FOR POR UNIDADE OU GERAL, AJUSTE O FILTRO ABAIXO. SEM A CHAVE CADASTRADA, NAO HA LIMITE. */
        DECLARE @LIM INT = TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'LIMITE_ENCAIXES_DIA'));
        IF @LIM IS NOT NULL AND (SELECT COUNT(*) FROM DBO.[CONSULTA]
                                 WHERE [CODIGO_PROFISSIONAL] = @CODIGO_PROFISSIONAL AND [ENCAIXE] = 1
                                   AND [STATUS] NOT IN ('CANCELADA', 'REMARCADA')
                                   AND CONVERT(DATE, [DATA_INICIO]) = CONVERT(DATE, @DATA_INICIO)) >= @LIM
            THROW 50003, 'Limite de encaixes do dia atingido.', 1;
    END;

    INSERT INTO DBO.[CONSULTA] ([CODIGO_PACIENTE], [CODIGO_PROFISSIONAL], [CODIGO_ESPECIALIDADE], [CODIGO_UNIDADE], [CODIGO_SALA], [MODALIDADE], [LINK_ONLINE],
        [TIPO_ATENDIMENTO], [CODIGO_CONVENIO], [NUMERO_CARTEIRINHA], [DATA_INICIO], [DATA_FIM], [VALOR], [CODIGO_PAGAMENTO], [PAGAMENTO_CONFIRMADO],
        [DATA_PAGAMENTO], [PAGAMENTO_CONFIRMADO_USUARIO], [STATUS], [CODIGO_CONSULTA_ORIGEM], [ENCAIXE], [CRIACAO_USUARIO],
        [CREDENCIAMENTO_LIBERADO_POR], [CREDENCIAMENTO_JUSTIFICATIVA])
    VALUES (@CODIGO_PACIENTE, @CODIGO_PROFISSIONAL, @CODIGO_ESPECIALIDADE, @CODIGO_UNIDADE, @CODIGO_SALA, @MODALIDADE, @LINK_ONLINE,
        @TIPO_ATENDIMENTO, @CODIGO_CONVENIO, @NUMERO_CARTEIRINHA, @DATA_INICIO, @DATA_FIM, @VALOR, @CODIGO_PAGAMENTO, @PAGAMENTO_CONFIRMADO,
        CASE WHEN @PAGAMENTO_CONFIRMADO = 1 THEN SYSUTCDATETIME() END, CASE WHEN @PAGAMENTO_CONFIRMADO = 1 THEN @CODIGO_USUARIO END,
        'AGENDADA', @CODIGO_CONSULTA_ORIGEM, @ENCAIXE, @CODIGO_USUARIO,
        @LIBERAR_POR, @LIBERAR_JUST);

    SET @CODIGO_CONSULTA = SCOPE_IDENTITY();
    SELECT @CODIGO_PUBLIC = [CODIGO_PUBLIC] FROM DBO.[CONSULTA] WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    INSERT INTO DBO.[CONSULTA_STATUS_HISTORICO] ([CODIGO_CONSULTA], [STATUS_ANTERIOR], [STATUS_NOVO], [CODIGO_USUARIO])
    VALUES (@CODIGO_CONSULTA, NULL, 'AGENDADA', @CODIGO_USUARIO);

    COMMIT TRANSACTION;
END;
GO

CREATE OR ALTER PROCEDURE DBO.USP_CONSULTA_REMARCAR
    @CODIGO_CONSULTA INT, @NOVO_INICIO DATETIME2(0), @NOVO_FIM DATETIME2(0) = NULL, @MOTIVO NVARCHAR(500),
    @CODIGO_PROFISSIONAL INT = NULL, @CODIGO_ESPECIALIDADE INT = NULL, @CODIGO_UNIDADE INT = NULL, @CODIGO_SALA INT = NULL,
    @ENCAIXE BIT = 0, @VERSAO BINARY(8), @CODIGO_USUARIO INT,
    @LIBERACAO_USUARIO INT = NULL, @LIBERACAO_JUSTIFICATIVA NVARCHAR(500) = NULL,
    @CODIGO_CONSULTA_NOVA INT OUTPUT, @CODIGO_PUBLIC UNIQUEIDENTIFIER OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NULLIF(LTRIM(RTRIM(@MOTIVO)), '') IS NULL THROW 50008, 'O motivo é obrigatório na remarcação.', 1;
    IF @NOVO_FIM IS NULL
        SET @NOVO_FIM = DATEADD(MINUTE, ISNULL(TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'DURACAO_PADRAO_CONSULTA_MIN')), 45), @NOVO_INICIO);

    BEGIN TRANSACTION;

    DECLARE @PACIENTE INT, @PROF_ORIG INT, @ESP_ORIG INT, @UNI_ORIG INT, @SALA_ORIG INT, @MODALIDADE NVARCHAR(10), @TIPO NVARCHAR(10);
    DECLARE @CONVENIO INT, @CARTEIRINHA NVARCHAR(30), @VALOR DECIMAL(10,2), @FORMA INT, @PAG BIT, @DATA_PAG DATETIME2(0), @PAG_USUARIO INT;
    DECLARE @STATUS NVARCHAR(20), @VERS BINARY(8), @LIB_ORIG INT, @LIB_JUST NVARCHAR(500);
    SELECT @PACIENTE = [CODIGO_PACIENTE], @PROF_ORIG = [CODIGO_PROFISSIONAL], @ESP_ORIG = [CODIGO_ESPECIALIDADE], @UNI_ORIG = [CODIGO_UNIDADE],
           @SALA_ORIG = [CODIGO_SALA], @MODALIDADE = [MODALIDADE], @TIPO = [TIPO_ATENDIMENTO], @CONVENIO = [CODIGO_CONVENIO],
           @CARTEIRINHA = [NUMERO_CARTEIRINHA], @VALOR = [VALOR], @FORMA = [CODIGO_PAGAMENTO], @PAG = [PAGAMENTO_CONFIRMADO],
           @DATA_PAG = [DATA_PAGAMENTO], @PAG_USUARIO = [PAGAMENTO_CONFIRMADO_USUARIO], @STATUS = [STATUS], @VERS = [VERSAO],
           @LIB_ORIG = [CREDENCIAMENTO_LIBERADO_POR], @LIB_JUST = [CREDENCIAMENTO_JUSTIFICATIVA]
    FROM DBO.[CONSULTA] WITH (UPDLOCK, ROWLOCK)
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    IF @STATUS IS NULL THROW 50005, 'Consulta inexistente.', 1;
    IF @VERS <> @VERSAO THROW 50004, 'A consulta foi alterada por outro usuário. Recarregue e tente novamente.', 1;
    IF @STATUS NOT IN ('AGENDADA', 'CONFIRMADA')
        THROW 50013, 'Só é possível remarcar consulta agendada ou confirmada.', 1;

    DECLARE @PROF_NOVO INT = ISNULL(@CODIGO_PROFISSIONAL, @PROF_ORIG);
    DECLARE @ESP_NOVA  INT = ISNULL(@CODIGO_ESPECIALIDADE, @ESP_ORIG);
    DECLARE @UNI_NOVA  INT = ISNULL(@CODIGO_UNIDADE, @UNI_ORIG);
    /* SALA: SEM UNIDADE NEM SALA INFORMADAS, MANTEM A ORIGINAL; SE TROCAR DE UNIDADE, A APLICACAO INFORMA A NOVA SALA. */
    DECLARE @SALA_NOVA INT = CASE WHEN @CODIGO_UNIDADE IS NULL AND @CODIGO_SALA IS NULL THEN @SALA_ORIG ELSE @CODIGO_SALA END;

    /* CREDENCIAMENTO DO CONVENIO (RN35) NA NOVA DATA, UNIDADE E ESPECIALIDADE. A LIBERACAO DO ADMINISTRADOR E MANTIDA SE A UNIDADE
       E A ESPECIALIDADE NAO MUDAM; EM OUTRO CASO, O ADMINISTRADOR PRECISA LIBERAR DE NOVO, COM JUSTIFICATIVA. */
    DECLARE @LIBERAR_POR INT = NULL, @LIBERAR_JUST NVARCHAR(500) = NULL;
    IF @CONVENIO IS NOT NULL
       AND DBO.FN_CREDENCIADO(@CONVENIO, @UNI_NOVA, @ESP_NOVA, CONVERT(DATE, DATEADD(HOUR, -3, @NOVO_INICIO))) = 0
    BEGIN
        IF @LIBERACAO_USUARIO IS NOT NULL
        BEGIN
            IF NULLIF(LTRIM(RTRIM(@LIBERACAO_JUSTIFICATIVA)), '') IS NULL
                THROW 50071, 'Informe a justificativa da liberação do credenciamento.', 1;
            IF NOT EXISTS (SELECT 1 FROM DBO.[USUARIO] AS U JOIN DBO.[PERFIL_ACESSO] AS P ON P.[CODIGO_PERFIL] = U.[CODIGO_PERFIL]
                           WHERE U.[CODIGO_USUARIO] = @LIBERACAO_USUARIO AND U.[ATIVO] = 1 AND P.[PROTEGIDO] = 1)
                THROW 50072, 'Somente o administrador ativo pode liberar consulta sem credenciamento.', 1;
            SET @LIBERAR_POR = @LIBERACAO_USUARIO;
            SET @LIBERAR_JUST = LTRIM(RTRIM(@LIBERACAO_JUSTIFICATIVA));
        END
        ELSE IF @LIB_ORIG IS NOT NULL AND @UNI_NOVA = @UNI_ORIG AND @ESP_NOVA = @ESP_ORIG
        BEGIN
            SET @LIBERAR_POR = @LIB_ORIG;
            SET @LIBERAR_JUST = @LIB_JUST;
        END
        ELSE
            THROW 50070, 'Convênio sem credenciamento aprovado para esta unidade e especialidade na data da consulta.', 1;
    END;

    /* RESERVA DAS AGENDAS EM ORDEM CRESCENTE DE PROFISSIONAL. */
    DECLARE @P1 INT = CASE WHEN @PROF_NOVO < @PROF_ORIG THEN @PROF_NOVO ELSE @PROF_ORIG END;
    DECLARE @P2 INT = CASE WHEN @PROF_NOVO < @PROF_ORIG THEN @PROF_ORIG ELSE @PROF_NOVO END;
    DECLARE @RECURSO NVARCHAR(100), @R INT;
    SET @RECURSO = N'AGENDA_PROFISSIONAL_' + CONVERT(NVARCHAR(10), @P1);
    EXEC @R = SP_GETAPPLOCK @RESOURCE = @RECURSO, @LOCKMODE = 'EXCLUSIVE', @LOCKOWNER = 'TRANSACTION', @LOCKTIMEOUT = 10000;
    IF @R < 0 THROW 50001, 'Agenda do profissional em uso por outra operação. Tente novamente.', 1;
    IF @P2 <> @P1
    BEGIN
        SET @RECURSO = N'AGENDA_PROFISSIONAL_' + CONVERT(NVARCHAR(10), @P2);
        EXEC @R = SP_GETAPPLOCK @RESOURCE = @RECURSO, @LOCKMODE = 'EXCLUSIVE', @LOCKOWNER = 'TRANSACTION', @LOCKTIMEOUT = 10000;
        IF @R < 0 THROW 50001, 'Agenda do profissional em uso por outra operação. Tente novamente.', 1;
    END;

    /* A ORIGINAL SAI DA AGENDA ANTES DA CONFERENCIA DE SOBREPOSICAO (REMARCADAS NAO CONTAM, RN09). */
    UPDATE DBO.[CONSULTA] SET [STATUS] = 'REMARCADA', [DATA_ATUALIZACAO] = SYSUTCDATETIME() WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;
    INSERT INTO DBO.[CONSULTA_STATUS_HISTORICO] ([CODIGO_CONSULTA], [STATUS_ANTERIOR], [STATUS_NOVO], [MOTIVO], [CODIGO_USUARIO])
    VALUES (@CODIGO_CONSULTA, @STATUS, 'REMARCADA', LTRIM(RTRIM(@MOTIVO)), @CODIGO_USUARIO);

    IF EXISTS (SELECT 1 FROM DBO.[CONSULTA] WITH (UPDLOCK, HOLDLOCK)
               WHERE [CODIGO_PROFISSIONAL] = @PROF_NOVO
                 AND [STATUS] NOT IN ('CANCELADA', 'REMARCADA')
                 AND [DATA_INICIO] < @NOVO_FIM AND [DATA_FIM] > @NOVO_INICIO)
        THROW 50002, 'Horário indisponível: o profissional já tem consulta nesse intervalo (RN09).', 1;

    IF @ENCAIXE = 1
    BEGIN
        DECLARE @LIM INT = TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'LIMITE_ENCAIXES_DIA'));
        IF @LIM IS NOT NULL AND (SELECT COUNT(*) FROM DBO.[CONSULTA]
                                 WHERE [CODIGO_PROFISSIONAL] = @PROF_NOVO AND [ENCAIXE] = 1
                                   AND [STATUS] NOT IN ('CANCELADA', 'REMARCADA')
                                   AND CONVERT(DATE, [DATA_INICIO]) = CONVERT(DATE, @NOVO_INICIO)) >= @LIM
            THROW 50003, 'Limite de encaixes do dia atingido.', 1;
    END;

    INSERT INTO DBO.[CONSULTA] ([CODIGO_PACIENTE], [CODIGO_PROFISSIONAL], [CODIGO_ESPECIALIDADE], [CODIGO_UNIDADE], [CODIGO_SALA], [MODALIDADE], [LINK_ONLINE],
        [TIPO_ATENDIMENTO], [CODIGO_CONVENIO], [NUMERO_CARTEIRINHA], [DATA_INICIO], [DATA_FIM], [VALOR], [CODIGO_PAGAMENTO], [PAGAMENTO_CONFIRMADO],
        [DATA_PAGAMENTO], [PAGAMENTO_CONFIRMADO_USUARIO], [STATUS], [CODIGO_CONSULTA_ORIGEM], [ENCAIXE], [CRIACAO_USUARIO],
        [CREDENCIAMENTO_LIBERADO_POR], [CREDENCIAMENTO_JUSTIFICATIVA])
    VALUES (@PACIENTE, @PROF_NOVO, @ESP_NOVA, @UNI_NOVA, @SALA_NOVA, @MODALIDADE, NULL,
        @TIPO, @CONVENIO, @CARTEIRINHA, @NOVO_INICIO, @NOVO_FIM, @VALOR, @FORMA, @PAG,
        @DATA_PAG, @PAG_USUARIO, 'AGENDADA', @CODIGO_CONSULTA, @ENCAIXE, @CODIGO_USUARIO,
        @LIBERAR_POR, @LIBERAR_JUST);

    SET @CODIGO_CONSULTA_NOVA = SCOPE_IDENTITY();
    SELECT @CODIGO_PUBLIC = [CODIGO_PUBLIC] FROM DBO.[CONSULTA] WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA_NOVA;

    INSERT INTO DBO.[CONSULTA_STATUS_HISTORICO] ([CODIGO_CONSULTA], [STATUS_ANTERIOR], [STATUS_NOVO], [CODIGO_USUARIO])
    VALUES (@CODIGO_CONSULTA_NOVA, NULL, 'AGENDADA', @CODIGO_USUARIO);

    COMMIT TRANSACTION;
END;
GO

/* ================== 6. AVISO A RECEPCAO (J4) ==================
   QUANDO UM CREDENCIAMENTO DEIXA DE VALER (SITUACAO DIFERENTE DE APROVADO OU FIM DA VIGENCIA ALTERADO), A RECEPCAO RECEBE UMA
   NOTIFICACAO INTERNA COM A QUANTIDADE DE CONSULTAS FUTURAS AFETADAS. NENHUMA CONSULTA E CANCELADA OU ALTERADA. */
IF EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE [NAME] = 'CK_NOTIFICACAO_INTERNA_TIPO')
    ALTER TABLE DBO.[NOTIFICACAO_INTERNA] DROP CONSTRAINT CK_NOTIFICACAO_INTERNA_TIPO;
ALTER TABLE DBO.[NOTIFICACAO_INTERNA] ADD CONSTRAINT CK_NOTIFICACAO_INTERNA_TIPO CHECK ([TIPO] IN ('SEM_RESPOSTA_48H', 'SEM_RESPOSTA_24H', 'HORARIO_DISPONIVEL', 'CREDENCIAMENTO'));
GO
CREATE OR ALTER TRIGGER DBO.TRG_CREDENCIAMENTO_CONVENIO_AVISO ON DBO.[CREDENCIAMENTO_CONVENIO] AFTER UPDATE AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO DBO.[NOTIFICACAO_INTERNA] ([TIPO], [CODIGO_CONSULTA], [CODIGO_USUARIO_DESTINO], [MENSAGEM])
    SELECT 'CREDENCIAMENTO', NULL, NULL,
           LEFT(CONCAT(N'Credenciamento alterado: convênio ', CV.[NOME_FANTASIA], N', unidade ', U.[NOME_FANTASIA], N', especialidade ', E.[NOME],
                       N'. Consultas futuras sem credenciamento: ', X.[QTD], N'. Veja a lista de consultas sem credenciamento.'), 500)
    FROM INSERTED AS I
    JOIN DELETED AS D ON D.[CODIGO_CREDENCIAMENTO] = I.[CODIGO_CREDENCIAMENTO]
    JOIN DBO.[CONVENIO] AS CV ON CV.[CODIGO_CONVENIO] = I.[CODIGO_CONVENIO]
    JOIN DBO.[UNIDADE] AS U ON U.[CODIGO_UNIDADE] = I.[CODIGO_UNIDADE]
    JOIN DBO.[ESPECIALIDADE] AS E ON E.[CODIGO_ESPECIALIDADE] = I.[CODIGO_ESPECIALIDADE]
    CROSS APPLY (SELECT COUNT(*) AS [QTD] FROM DBO.[CONSULTA] AS C
                 WHERE C.[CODIGO_CONVENIO] = I.[CODIGO_CONVENIO] AND C.[CODIGO_UNIDADE] = I.[CODIGO_UNIDADE] AND C.[CODIGO_ESPECIALIDADE] = I.[CODIGO_ESPECIALIDADE]
                   AND C.[STATUS] IN ('AGENDADA', 'CONFIRMADA') AND C.[DATA_INICIO] >= SYSUTCDATETIME() AND C.[CREDENCIAMENTO_LIBERADO_POR] IS NULL
                   AND DBO.FN_CREDENCIADO(C.[CODIGO_CONVENIO], C.[CODIGO_UNIDADE], C.[CODIGO_ESPECIALIDADE], CONVERT(DATE, DATEADD(HOUR, -3, C.[DATA_INICIO]))) = 0) AS X
    WHERE X.[QTD] > 0
      AND (I.[SITUACAO] <> D.[SITUACAO] OR ISNULL(I.[DATA_FIM], '9999-12-31') <> ISNULL(D.[DATA_FIM], '9999-12-31') OR ISNULL(I.[DATA_INICIO], '9999-12-31') <> ISNULL(D.[DATA_INICIO], '9999-12-31'));
END;
GO

/* ================== 7. VIEW: CONSULTAS FUTURAS SEM CREDENCIAMENTO (J4) ================== */
CREATE OR ALTER VIEW DBO.VW_CONSULTA_SEM_CREDENCIAMENTO AS
SELECT C.[CODIGO_CONSULTA], C.[CODIGO_PUBLIC], C.[STATUS], C.[DATA_INICIO], C.[CODIGO_PACIENTE], C.[CODIGO_PROFISSIONAL],
       C.[CODIGO_ESPECIALIDADE], C.[CODIGO_UNIDADE], C.[CODIGO_CONVENIO]
FROM DBO.[CONSULTA] AS C
WHERE C.[CODIGO_CONVENIO] IS NOT NULL
  AND C.[STATUS] IN ('AGENDADA', 'CONFIRMADA')
  AND C.[DATA_INICIO] >= SYSUTCDATETIME()
  AND C.[CREDENCIAMENTO_LIBERADO_POR] IS NULL
  AND DBO.FN_CREDENCIADO(C.[CODIGO_CONVENIO], C.[CODIGO_UNIDADE], C.[CODIGO_ESPECIALIDADE], CONVERT(DATE, DATEADD(HOUR, -3, C.[DATA_INICIO]))) = 0;
GO
IF DATABASE_PRINCIPAL_ID('ROLE_DBA_ANALISE') IS NOT NULL GRANT SELECT ON DBO.VW_CONSULTA_SEM_CREDENCIAMENTO TO ROLE_DBA_ANALISE;
GO

