        CONSTRAINT FK_CREDENCIAMENTO_CONVENIO_CRIACAO_USUARIO FOREIGN KEY ([CRIACAO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO]),
        CONSTRAINT FK_CREDENCIAMENTO_CONVENIO_ATUALIZACAO_USUARIO FOREIGN KEY ([ATUALIZACAO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO]),
        CONSTRAINT CK_CREDENCIAMENTO_CONVENIO_SITUACAO CHECK ([SITUACAO] IN ('APROVADO', 'EM_ANALISE', 'NAO_CREDENCIADO')),
        CONSTRAINT CK_CREDENCIAMENTO_CONVENIO_VIGENCIA CHECK (([SITUACAO] <> 'APROVADO' OR [DATA_INICIO] IS NOT NULL) AND ([DATA_FIM] IS NULL OR [DATA_INICIO] IS NULL OR [DATA_FIM] >= [DATA_INICIO]))
    );
END;
GO

/* ================== 2. FUNCAO: O CONVENIO ESTA CREDENCIADO NA DATA? ================== */
CREATE OR ALTER FUNCTION DBO.FN_CREDENCIADO (@CODIGO_CONVENIO INT, @CODIGO_UNIDADE INT, @CODIGO_ESPECIALIDADE INT, @DATA DATE)
RETURNS BIT
AS
BEGIN
    RETURN CASE WHEN EXISTS (SELECT 1 FROM DBO.[CREDENCIAMENTO_CONVENIO]
                             WHERE [CODIGO_CONVENIO] = @CODIGO_CONVENIO AND [CODIGO_UNIDADE] = @CODIGO_UNIDADE AND [CODIGO_ESPECIALIDADE] = @CODIGO_ESPECIALIDADE
                               AND [SITUACAO] = 'APROVADO' AND [DATA_INICIO] <= @DATA AND ([DATA_FIM] IS NULL OR [DATA_FIM] >= @DATA))
                THEN 1 ELSE 0 END;
END;
GO

