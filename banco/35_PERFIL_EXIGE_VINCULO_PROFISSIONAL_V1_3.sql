-- =====================================================================
-- SCRIPT 35 - PERFIL DE PROFISSIONAL: EXIGE VINCULO COM PROFISSIONAL (V1.3)
-- TABELA: PERFIL_ACESSO
-- EXIGE_VINCULO_PROFISSIONAL: 1 = USUARIO DESTE PERFIL SO USA O SISTEMA SE TIVER "PROFISSIONAL VINCULADO".
--   SEM O VINCULO O SERVIDOR NEGA O ACESSO (NENHUM PACIENTE/CONSULTA APARECE). O ADMINISTRADOR NAO E AFETADO.
-- MARCA AUTOMATICAMENTE OS PERFIS CUJO NOME COMECA COM "MEDICO"/"PROFISSIONAL" (CONFIRA NA TELA DE PERFIS).
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.PERFIL_ACESSO', 'EXIGE_VINCULO_PROFISSIONAL') IS NULL
    ALTER TABLE DBO.[PERFIL_ACESSO] ADD [EXIGE_VINCULO_PROFISSIONAL] BIT NOT NULL
        CONSTRAINT DF_PERFIL_ACESSO_EXIGE_VINCULO DEFAULT (0);
GO

UPDATE DBO.PERFIL_ACESSO
SET EXIGE_VINCULO_PROFISSIONAL = 1
WHERE PROTEGIDO = 0
  AND EXIGE_VINCULO_PROFISSIONAL = 0
  AND (NOME LIKE N'M_DICO%' OR NOME LIKE N'PROFISSIONAL%');
GO

SELECT CODIGO_PERFIL, NOME, EXIGE_VINCULO_PROFISSIONAL FROM DBO.PERFIL_ACESSO ORDER BY NOME;
GO
