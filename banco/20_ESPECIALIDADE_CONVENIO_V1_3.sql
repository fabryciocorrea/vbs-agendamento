-- SCRIPT 20 - ESPECIALIDADES DO CONVENIO (V1.3)
-- NOVA TABELA DBO.CONVENIO_ESPECIALIDADE (UM CONVENIO PODE TER VARIAS ESPECIALIDADES).
-- CONVENIOS JA CADASTRADOS RECEBEM AS ESPECIALIDADES QUE JA APARECEM NOS SEUS CREDENCIAMENTOS.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF OBJECT_ID('DBO.CONVENIO_ESPECIALIDADE', 'U') IS NULL
    CREATE TABLE DBO.[CONVENIO_ESPECIALIDADE] (
        [CODIGO_CONVENIO]      INT NOT NULL,
        [CODIGO_ESPECIALIDADE] INT NOT NULL,
        CONSTRAINT PK_CONVENIO_ESPECIALIDADE PRIMARY KEY ([CODIGO_CONVENIO], [CODIGO_ESPECIALIDADE]),
        CONSTRAINT FK_CONVENIO_ESPECIALIDADE_CONVENIO FOREIGN KEY ([CODIGO_CONVENIO]) REFERENCES DBO.[CONVENIO] ([CODIGO_CONVENIO]),
        CONSTRAINT FK_CONVENIO_ESPECIALIDADE_ESPECIALIDADE FOREIGN KEY ([CODIGO_ESPECIALIDADE]) REFERENCES DBO.[ESPECIALIDADE] ([CODIGO_ESPECIALIDADE])
    );
GO

INSERT INTO DBO.CONVENIO_ESPECIALIDADE (CODIGO_CONVENIO, CODIGO_ESPECIALIDADE)
SELECT DISTINCT K.CODIGO_CONVENIO, K.CODIGO_ESPECIALIDADE
FROM DBO.CREDENCIAMENTO_CONVENIO K
WHERE NOT EXISTS (SELECT 1 FROM DBO.CONVENIO_ESPECIALIDADE X
                  WHERE X.CODIGO_CONVENIO = K.CODIGO_CONVENIO AND X.CODIGO_ESPECIALIDADE = K.CODIGO_ESPECIALIDADE);
GO

SELECT C.CODIGO_CONVENIO, C.RAZAO_SOCIAL, E.NOME AS ESPECIALIDADE
FROM DBO.CONVENIO C
LEFT JOIN DBO.CONVENIO_ESPECIALIDADE CE ON CE.CODIGO_CONVENIO = C.CODIGO_CONVENIO
LEFT JOIN DBO.ESPECIALIDADE E ON E.CODIGO_ESPECIALIDADE = CE.CODIGO_ESPECIALIDADE
ORDER BY C.CODIGO_CONVENIO, E.NOME;
GO
