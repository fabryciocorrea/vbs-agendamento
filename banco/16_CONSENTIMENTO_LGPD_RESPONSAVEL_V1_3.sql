-- TABELA NOVA, SOMENTE INCLUSAO (CADA ALTERACAO E UMA LINHA NOVA), COMO A DO PACIENTE.
-- O RESPONSAVEL LEGAL NAO TEM CONVENIO NEM PROFISSIONAL RESPONSAVEL (SAO DO PACIENTE).
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF OBJECT_ID('DBO.CONSENTIMENTO_LGPD_RESPONSAVEL', 'U') IS NULL
BEGIN
    CREATE TABLE DBO.[CONSENTIMENTO_LGPD_RESPONSAVEL] (
        [CODIGO_CONSENTIMENTO] INT IDENTITY(1,1) NOT NULL,
        [CODIGO_RESPONSAVEL] INT NOT NULL,
        [FINALIDADE] NVARCHAR(30) NOT NULL,
        [CONCEDIDO] BIT NOT NULL,
        [DATA_REGISTRO] DATETIME2(0) NOT NULL CONSTRAINT DF_CONSENTIMENTO_LGPD_RESPONSAVEL_DATA_REGISTRO DEFAULT SYSUTCDATETIME(),
        [ORIGEM] NVARCHAR(20) NOT NULL,
        [REGISTRO_USUARIO] INT NULL,
        CONSTRAINT PK_CONSENTIMENTO_LGPD_RESPONSAVEL PRIMARY KEY ([CODIGO_CONSENTIMENTO]),
        CONSTRAINT CK_CONSENTIMENTO_LGPD_RESPONSAVEL_FINALIDADE CHECK ([FINALIDADE] IN ('TRATAMENTO_DADOS','CONTATO_SMS_WHATSAPP')),
        CONSTRAINT CK_CONSENTIMENTO_LGPD_RESPONSAVEL_ORIGEM CHECK ([ORIGEM] IN ('PRESENCIAL','TELEFONE','SISTEMA')),
        CONSTRAINT FK_CONSENTIMENTO_LGPD_RESPONSAVEL_CODIGO_RESPONSAVEL FOREIGN KEY ([CODIGO_RESPONSAVEL]) REFERENCES DBO.[RESPONSAVEL_LEGAL] ([CODIGO_RESPONSAVEL]),
        CONSTRAINT FK_CONSENTIMENTO_LGPD_RESPONSAVEL_REGISTRO_USUARIO FOREIGN KEY ([REGISTRO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO])
    );
    CREATE INDEX IX_CONSENTIMENTO_LGPD_RESPONSAVEL_RESPONSAVEL ON DBO.[CONSENTIMENTO_LGPD_RESPONSAVEL] ([CODIGO_RESPONSAVEL], [FINALIDADE], [DATA_REGISTRO]);
END;
GO

-- SOMENTE INCLUSAO: CADA ALTERACAO DE CONSENTIMENTO E UMA LINHA NOVA.
CREATE OR ALTER TRIGGER DBO.TRG_CONSENTIMENTO_LGPD_RESPONSAVEL_SOMENTE_INCLUSAO ON DBO.[CONSENTIMENTO_LGPD_RESPONSAVEL] INSTEAD OF UPDATE, DELETE AS
BEGIN
    SET NOCOUNT ON;
    THROW 50023, 'CONSENTIMENTO_LGPD_RESPONSAVEL é somente de inclusão: cada alteração é uma nova linha.', 1;
END;
GO

IF DATABASE_PRINCIPAL_ID('ROLE_APP_AGENDAMENTO') IS NOT NULL
BEGIN
    GRANT SELECT, INSERT ON DBO.[CONSENTIMENTO_LGPD_RESPONSAVEL] TO ROLE_APP_AGENDAMENTO;
    DENY UPDATE, DELETE ON DBO.[CONSENTIMENTO_LGPD_RESPONSAVEL] TO ROLE_APP_AGENDAMENTO;
END;
GO

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'CONSENTIMENTO_LGPD_RESPONSAVEL'
ORDER BY ORDINAL_POSITION;
GO
