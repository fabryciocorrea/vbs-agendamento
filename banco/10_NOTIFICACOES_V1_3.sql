/* VIVER BEM SAUDE - SCRIPT 10 - NOTIFICACOES: AJUSTES DE TABELAS PARA O BLOCO 6 DA API
   EXECUTAR DEPOIS DOS SCRIPTS 01, 02, 05, 06, 08 E 09, NO BANCO VBSAGENDA. PODE SER EXECUTADO MAIS DE UMA VEZ.

   O ENVIO DAS MENSAGENS E FEITO PELO SERVICO EM SEGUNDO PLANO DA APLICACAO; ESTE SCRIPT SO PREPARA AS TABELAS:
   - NOVOS TIPOS DE MENSAGEM AO PACIENTE (CANCELAMENTO E REMARCACAO) E NOVO STATUS DE ENVIO (CANCELADA);
   - NOVOS TIPOS DE AVISO INTERNO (CONTATO_MANUAL, RESPOSTA_PACIENTE E FALHA_ENVIO);
   - TELEFONE USADO NO ENVIO (PARA LIGAR A RESPOSTA DO PACIENTE A MENSAGEM);
   - TABELA WEBHOOK_EVENTO (IDEMPOTENCIA: EVENTO REPETIDO DO PROVEDOR E IGNORADO);
   - PARAMETRO DO AVISO FINAL DE SEM RESPOSTA (12 HORAS ANTES DA CONSULTA). */

/* ================== 1. MENSAGENS AO PACIENTE ================== */
IF EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE [NAME] = 'CK_NOTIFICACAO_AGENDAMENTO_TIPO')
    ALTER TABLE DBO.[NOTIFICACAO_AGENDAMENTO] DROP CONSTRAINT CK_NOTIFICACAO_AGENDAMENTO_TIPO;
ALTER TABLE DBO.[NOTIFICACAO_AGENDAMENTO] ADD CONSTRAINT CK_NOTIFICACAO_AGENDAMENTO_TIPO CHECK ([TIPO] IN ('CONFIRMACAO_48H', 'LEMBRETE_24H', 'CANCELAMENTO', 'REMARCACAO'));
GO
IF EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE [NAME] = 'CK_NOTIFICACAO_AGENDAMENTO_STATUS_ENTREGA')
    ALTER TABLE DBO.[NOTIFICACAO_AGENDAMENTO] DROP CONSTRAINT CK_NOTIFICACAO_AGENDAMENTO_STATUS_ENTREGA;
ALTER TABLE DBO.[NOTIFICACAO_AGENDAMENTO] ADD CONSTRAINT CK_NOTIFICACAO_AGENDAMENTO_STATUS_ENTREGA CHECK ([STATUS_ENTREGA] IN ('PENDENTE', 'ENVIADA', 'ENTREGUE', 'LIDA', 'FALHA', 'CANCELADA'));
GO
IF COL_LENGTH('DBO.NOTIFICACAO_AGENDAMENTO', 'TELEFONE') IS NULL
    ALTER TABLE DBO.[NOTIFICACAO_AGENDAMENTO] ADD [TELEFONE] NVARCHAR(20) NULL;   -- TELEFONE (SO DIGITOS, COM DDI) USADO NO ENVIO
GO
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_NOTIFICACAO_AGENDAMENTO_PENDENTE' AND [OBJECT_ID] = OBJECT_ID('DBO.NOTIFICACAO_AGENDAMENTO'))
    CREATE INDEX IX_NOTIFICACAO_AGENDAMENTO_PENDENTE ON DBO.[NOTIFICACAO_AGENDAMENTO] ([STATUS_ENTREGA], [DATA_AGENDADA]);   -- BUSCA DO SERVICO DE ENVIO
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_NOTIFICACAO_AGENDAMENTO_TELEFONE' AND [OBJECT_ID] = OBJECT_ID('DBO.NOTIFICACAO_AGENDAMENTO'))
    CREATE INDEX IX_NOTIFICACAO_AGENDAMENTO_TELEFONE ON DBO.[NOTIFICACAO_AGENDAMENTO] ([TELEFONE], [DATA_ENVIO]);             -- LIGA A RESPOSTA A ULTIMA MENSAGEM DO TELEFONE
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_NOTIFICACAO_AGENDAMENTO_PROVEDOR' AND [OBJECT_ID] = OBJECT_ID('DBO.NOTIFICACAO_AGENDAMENTO'))
    CREATE INDEX IX_NOTIFICACAO_AGENDAMENTO_PROVEDOR ON DBO.[NOTIFICACAO_AGENDAMENTO] ([CODIGO_PROVEDOR_MENSAGEM]);          -- LIGA O STATUS DE ENTREGA A MENSAGEM
GO

/* ================== 2. AVISOS INTERNOS DA RECEPCAO ================== */
IF EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE [NAME] = 'CK_NOTIFICACAO_INTERNA_TIPO')
    ALTER TABLE DBO.[NOTIFICACAO_INTERNA] DROP CONSTRAINT CK_NOTIFICACAO_INTERNA_TIPO;
ALTER TABLE DBO.[NOTIFICACAO_INTERNA] ADD CONSTRAINT CK_NOTIFICACAO_INTERNA_TIPO CHECK ([TIPO] IN
    ('SEM_RESPOSTA_48H', 'SEM_RESPOSTA_24H', 'HORARIO_DISPONIVEL', 'CREDENCIAMENTO', 'CONTATO_MANUAL', 'RESPOSTA_PACIENTE', 'FALHA_ENVIO'));
GO
IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE [NAME] = 'IX_NOTIFICACAO_INTERNA_NAO_LIDA' AND [OBJECT_ID] = OBJECT_ID('DBO.NOTIFICACAO_INTERNA'))
    CREATE INDEX IX_NOTIFICACAO_INTERNA_NAO_LIDA ON DBO.[NOTIFICACAO_INTERNA] ([DATA_LEITURA], [DATA_CRIACAO] DESC);
GO

/* ================== 3. EVENTOS DE WEBHOOK (IDEMPOTENCIA) ================== */
IF OBJECT_ID('DBO.WEBHOOK_EVENTO', 'U') IS NULL
BEGIN
    CREATE TABLE DBO.[WEBHOOK_EVENTO] (
        [CODIGO_WEBHOOK_EVENTO] BIGINT IDENTITY(1,1) NOT NULL,
        [TIPO]                  NVARCHAR(20) NOT NULL,                  -- STATUS_ENTREGA OU RESPOSTA
        [EVENTO_ID]             NVARCHAR(100) NOT NULL,                 -- IDENTIFICADOR DO EVENTO NO PROVEDOR
        [DATA_RECEBIDO]         DATETIME2(3) NOT NULL CONSTRAINT DF_WEBHOOK_EVENTO_DATA_RECEBIDO DEFAULT SYSUTCDATETIME(),
        [EFEITO]                NVARCHAR(40) NOT NULL,                  -- PROCESSADO OU IGNORADO_SEM_CORRESPONDENCIA
        CONSTRAINT PK_WEBHOOK_EVENTO PRIMARY KEY ([CODIGO_WEBHOOK_EVENTO]),
        CONSTRAINT UQ_WEBHOOK_EVENTO UNIQUE ([TIPO], [EVENTO_ID]),
        CONSTRAINT CK_WEBHOOK_EVENTO_TIPO CHECK ([TIPO] IN ('STATUS_ENTREGA', 'RESPOSTA')),
        CONSTRAINT CK_WEBHOOK_EVENTO_EFEITO CHECK ([EFEITO] IN ('PROCESSADO', 'IGNORADO_SEM_CORRESPONDENCIA'))
    );
END;
GO

/* ================== 4. PARAMETRO DO AVISO FINAL ================== */
INSERT INTO DBO.[PARAMETRO_SISTEMA] ([CHAVE_PARAMETRO], [VALOR], [DESCRICAO_PARAMETRO])
SELECT N'ALERTA_SEM_RESPOSTA_ANTECEDENCIA_H', N'12', N'Aviso final à recepção de quem continua sem retorno, em horas antes da consulta (RN07).'
WHERE NOT EXISTS (SELECT 1 FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'ALERTA_SEM_RESPOSTA_ANTECEDENCIA_H');
GO

/* CONFERENCIA: DEVE LISTAR 3 PARAMETROS DE NOTIFICACAO (48, 24 E 12) E A TABELA WEBHOOK_EVENTO. */
SELECT [CHAVE_PARAMETRO], [VALOR] FROM DBO.[PARAMETRO_SISTEMA]
WHERE [CHAVE_PARAMETRO] IN (N'CONFIRMACAO_ANTECEDENCIA_H', N'LEMBRETE_ANTECEDENCIA_H', N'ALERTA_SEM_RESPOSTA_ANTECEDENCIA_H') ORDER BY [CHAVE_PARAMETRO];
SELECT [NAME] FROM SYS.TABLES WHERE [NAME] = 'WEBHOOK_EVENTO';
GO

