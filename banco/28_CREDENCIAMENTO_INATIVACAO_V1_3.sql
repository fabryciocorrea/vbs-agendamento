/* ============================================================================================================
   SCRIPT 28 - INATIVACAO DO CREDENCIAMENTO E TROCA DE CONVENIO, UNIDADE E ESPECIALIDADE
   BANCO: VBSAGENDA (RODAR NO SSMS, DEPOIS DO SCRIPT 27)
   O QUE FAZ:
   1) COLUNA ATIVO EM CREDENCIAMENTO_CONVENIO (PADRAO 1). CREDENCIAMENTO INATIVO NAO VALE PARA AGENDAR (FN_CREDENCIADO).
   2) FN_CREDENCIADO PASSA A EXIGIR ATIVO = 1.
   3) GATILHO DE AVISO A RECEPCAO TAMBEM AVISA QUANDO O CREDENCIAMENTO E INATIVADO OU QUANDO SUA CHAVE (CONVENIO, UNIDADE,
      ESPECIALIDADE) MUDA (A CHAVE ANTIGA E A QUE DEIXA DE VALER). NENHUMA CONSULTA E CANCELADA OU ALTERADA.
   ============================================================================================================ */
SET NOCOUNT ON;
GO

IF COL_LENGTH('DBO.CREDENCIAMENTO_CONVENIO', 'ATIVO') IS NULL
    ALTER TABLE DBO.[CREDENCIAMENTO_CONVENIO] ADD [ATIVO] BIT NOT NULL CONSTRAINT DF_CREDENCIAMENTO_CONVENIO_ATIVO DEFAULT 1;
GO

CREATE OR ALTER FUNCTION DBO.FN_CREDENCIADO (@CODIGO_CONVENIO INT, @CODIGO_UNIDADE INT, @CODIGO_ESPECIALIDADE INT, @DATA DATE)
RETURNS BIT
AS
BEGIN
    RETURN CASE WHEN EXISTS (SELECT 1 FROM DBO.[CREDENCIAMENTO_CONVENIO]
                             WHERE [CODIGO_CONVENIO] = @CODIGO_CONVENIO AND [CODIGO_UNIDADE] = @CODIGO_UNIDADE AND [CODIGO_ESPECIALIDADE] = @CODIGO_ESPECIALIDADE
                               AND [ATIVO] = 1
                               AND [SITUACAO] = 'APROVADO' AND [DATA_INICIO] <= @DATA AND ([DATA_FIM] IS NULL OR [DATA_FIM] >= @DATA))
                THEN 1 ELSE 0 END;
END;
GO

CREATE OR ALTER TRIGGER DBO.TRG_CREDENCIAMENTO_CONVENIO_AVISO ON DBO.[CREDENCIAMENTO_CONVENIO] AFTER UPDATE AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO DBO.[NOTIFICACAO_INTERNA] ([TIPO], [CODIGO_CONSULTA], [CODIGO_USUARIO_DESTINO], [MENSAGEM])
    SELECT 'CREDENCIAMENTO', NULL, NULL,
           LEFT(CONCAT(N'Credenciamento alterado: convênio ', CV.[NOME_FANTASIA], N', unidade ', U.[NOME_FANTASIA], N', especialidade ', E.[NOME],
                       N'. Consultas futuras sem credenciamento: ', X.[QTD], N'. Veja a lista de consultas sem credenciamento.'), 500)
    FROM (
        /* SITUACAO, VIGENCIA OU ATIVO MUDARAM: VALE A CHAVE ATUAL */
        SELECT I.[CODIGO_CREDENCIAMENTO] AS [ID], I.[CODIGO_CONVENIO] AS [CV], I.[CODIGO_UNIDADE] AS [UN], I.[CODIGO_ESPECIALIDADE] AS [ES]
        FROM INSERTED AS I JOIN DELETED AS D ON D.[CODIGO_CREDENCIAMENTO] = I.[CODIGO_CREDENCIAMENTO]
        WHERE I.[SITUACAO] <> D.[SITUACAO] OR I.[ATIVO] <> D.[ATIVO]
           OR ISNULL(I.[DATA_FIM], '9999-12-31') <> ISNULL(D.[DATA_FIM], '9999-12-31')
           OR ISNULL(I.[DATA_INICIO], '9999-12-31') <> ISNULL(D.[DATA_INICIO], '9999-12-31')
        UNION
        /* CONVENIO, UNIDADE OU ESPECIALIDADE MUDARAM: A CHAVE ANTIGA DEIXOU DE VALER */
        SELECT D.[CODIGO_CREDENCIAMENTO], D.[CODIGO_CONVENIO], D.[CODIGO_UNIDADE], D.[CODIGO_ESPECIALIDADE]
        FROM INSERTED AS I JOIN DELETED AS D ON D.[CODIGO_CREDENCIAMENTO] = I.[CODIGO_CREDENCIAMENTO]
        WHERE I.[CODIGO_CONVENIO] <> D.[CODIGO_CONVENIO] OR I.[CODIGO_UNIDADE] <> D.[CODIGO_UNIDADE] OR I.[CODIGO_ESPECIALIDADE] <> D.[CODIGO_ESPECIALIDADE]
    ) AS CH
    JOIN DBO.[CONVENIO] AS CV ON CV.[CODIGO_CONVENIO] = CH.[CV]
    JOIN DBO.[UNIDADE] AS U ON U.[CODIGO_UNIDADE] = CH.[UN]
    JOIN DBO.[ESPECIALIDADE] AS E ON E.[CODIGO_ESPECIALIDADE] = CH.[ES]
    CROSS APPLY (SELECT COUNT(*) AS [QTD] FROM DBO.[CONSULTA] AS C
                 WHERE C.[CODIGO_CONVENIO] = CH.[CV] AND C.[CODIGO_UNIDADE] = CH.[UN] AND C.[CODIGO_ESPECIALIDADE] = CH.[ES]
                   AND C.[STATUS] IN ('AGENDADA', 'CONFIRMADA') AND C.[DATA_INICIO] >= SYSUTCDATETIME() AND C.[CREDENCIAMENTO_LIBERADO_POR] IS NULL
                   AND DBO.FN_CREDENCIADO(C.[CODIGO_CONVENIO], C.[CODIGO_UNIDADE], C.[CODIGO_ESPECIALIDADE], CONVERT(DATE, DATEADD(HOUR, -3, C.[DATA_INICIO]))) = 0) AS X
    WHERE X.[QTD] > 0;
END;
GO

/* CONFERENCIA: A COLUNA ATIVO DEVE EXISTIR E TODOS OS CREDENCIAMENTOS ATUAIS FICAM ATIVOS (1). */
SELECT [ATIVO], COUNT(*) AS [QUANTIDADE] FROM DBO.[CREDENCIAMENTO_CONVENIO] GROUP BY [ATIVO];
GO
