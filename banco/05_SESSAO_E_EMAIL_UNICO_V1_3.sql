/* VIVER BEM SAUDE - SCRIPT 05 - SESSAO POR INATIVIDADE (D1) E E-MAIL UNICO (D2)
   EXECUTAR DEPOIS DOS SCRIPTS 01, 02 E 03 (O 04 NAO SE APLICA A QUEM CRIOU O BANCO COM O 01 ATUAL).
   EXECUTAR UMA UNICA VEZ. */

/* D2: O E-MAIL PASSA A SER UNICO POR USUARIO (RECUPERACAO DE SENHA PELO E-MAIL).
   A COLLATION DO BANCO E CI: MAIUSCULAS E MINUSCULAS CONTAM COMO IGUAIS.
   SE JA HOUVER USUARIOS COM E-MAIL REPETIDO, CORRIJA ANTES (SELECT EMAIL, COUNT(*) FROM DBO.USUARIO GROUP BY EMAIL HAVING COUNT(*) > 1). */
ALTER TABLE DBO.[USUARIO] ADD CONSTRAINT UQ_USUARIO_EMAIL UNIQUE ([EMAIL]);
GO

/* D1: A SESSAO FICA REGISTRADA NO SERVIDOR. A API CONFERE A ULTIMA ATIVIDADE A CADA REQUISICAO:
   SE PASSARAM MAIS DE 30 MINUTOS, ENCERRA A SESSAO (MOTIVO INATIVIDADE); SE NAO, RENOVA A JANELA.
   LOGOUT, INATIVACAO DO USUARIO, BLOQUEIO E TROCA DE SENHA ENCERRAM AS SESSOES NA HORA. */
CREATE TABLE DBO.[SESSAO_USUARIO] (
    [CODIGO_SESSAO] BIGINT IDENTITY(1,1) NOT NULL,
    [CODIGO_USUARIO] INT NOT NULL,
    [TOKEN_HASH] NVARCHAR(128) NOT NULL,
    [DATA_CRIACAO] DATETIME2(0) NOT NULL CONSTRAINT DF_SESSAO_USUARIO_DATA_CRIACAO DEFAULT SYSUTCDATETIME(),
    [DATA_ULTIMA_ATIVIDADE] DATETIME2(0) NOT NULL CONSTRAINT DF_SESSAO_USUARIO_DATA_ULTIMA_ATIVIDADE DEFAULT SYSUTCDATETIME(),
    [DATA_ENCERRAMENTO] DATETIME2(0) NULL,
    [MOTIVO_ENCERRAMENTO] NVARCHAR(20) NULL,
    [IP] NVARCHAR(45) NULL,
    CONSTRAINT PK_SESSAO_USUARIO PRIMARY KEY ([CODIGO_SESSAO])
);
GO
ALTER TABLE DBO.[SESSAO_USUARIO] ADD CONSTRAINT UQ_SESSAO_USUARIO_TOKEN_HASH UNIQUE ([TOKEN_HASH]);
ALTER TABLE DBO.[SESSAO_USUARIO] ADD CONSTRAINT CK_SESSAO_USUARIO_MOTIVO CHECK ([MOTIVO_ENCERRAMENTO] IS NULL OR [MOTIVO_ENCERRAMENTO] IN ('LOGOUT','INATIVIDADE','USUARIO_INATIVADO','USUARIO_BLOQUEADO','SENHA_ALTERADA'));
ALTER TABLE DBO.[SESSAO_USUARIO] ADD CONSTRAINT CK_SESSAO_USUARIO_ENCERRAMENTO CHECK (([DATA_ENCERRAMENTO] IS NULL AND [MOTIVO_ENCERRAMENTO] IS NULL) OR ([DATA_ENCERRAMENTO] IS NOT NULL AND [MOTIVO_ENCERRAMENTO] IS NOT NULL));
ALTER TABLE DBO.[SESSAO_USUARIO] ADD CONSTRAINT FK_SESSAO_USUARIO_CODIGO_USUARIO FOREIGN KEY ([CODIGO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO]);
CREATE INDEX IX_SESSAO_USUARIO_USUARIO ON DBO.[SESSAO_USUARIO] ([CODIGO_USUARIO], [DATA_ENCERRAMENTO]);
GO
/* A ROLE DA API (ROLE_APP_AGENDAMENTO) JA TEM SELECT, INSERT E UPDATE NO SCHEMA DBO, ENTAO ACESSA A NOVA TABELA. */

/* VIEW PARA ANALISE */
CREATE OR ALTER VIEW DBO.VW_SESSAO_USUARIO AS
SELECT S.CODIGO_SESSAO, S.CODIGO_USUARIO, U.NOME_USUARIO AS LOGIN, U.NOME_COMPLETO AS USUARIO,
       S.DATA_CRIACAO, S.DATA_ULTIMA_ATIVIDADE, S.DATA_ENCERRAMENTO, S.MOTIVO_ENCERRAMENTO, S.IP
FROM DBO.SESSAO_USUARIO S
JOIN DBO.USUARIO U ON U.CODIGO_USUARIO = S.CODIGO_USUARIO;
GO
IF DATABASE_PRINCIPAL_ID('ROLE_DBA_ANALISE') IS NOT NULL GRANT SELECT ON DBO.VW_SESSAO_USUARIO TO ROLE_DBA_ANALISE;
GO
