-- =====================================================================
-- SCRIPT 31 - PERMISSAO "CANCELAR" NOS PERFIS DE ACESSO (V1.3)
-- NOVA COLUNA PERFIL_TELA_PERMISSAO.PODE_CANCELAR. SEPARA "CANCELAR" DE "EDITAR": EDITAR ALTERA DADOS DO AGENDAMENTO;
-- CANCELAR LIBERA O CANCELAMENTO DA CONSULTA (STATUS DA CONSULTA), DA GUIA DO CONVENIO (FATURAMENTO) E DO ITEM DA LISTA DE ESPERA.
-- PARA NAO TIRAR ACESSO DE QUEM JA USAVA, OS PERFIS QUE TINHAM EDITAR NESSAS TRES TELAS RECEBEM CANCELAR.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.PERFIL_TELA_PERMISSAO', 'PODE_CANCELAR') IS NULL
    ALTER TABLE DBO.PERFIL_TELA_PERMISSAO ADD [PODE_CANCELAR] BIT NOT NULL CONSTRAINT DF_PERFIL_TELA_PERMISSAO_PODE_CANCELAR DEFAULT 0;
GO

UPDATE P SET P.[PODE_CANCELAR] = 1
FROM DBO.PERFIL_TELA_PERMISSAO AS P
JOIN DBO.TELA_SISTEMA AS T ON T.[ID_TELA_SISTEMA] = P.[CODIGO_TELA]
WHERE T.[CODIGO] IN ('consulta.status', 'faturamento.financeiro', 'listaespera.cadastro')
  AND P.[PODE_EDITAR] = 1 AND P.[PODE_CANCELAR] = 0;
GO

PRINT 'SCRIPT 31 EXECUTADO';
GO
