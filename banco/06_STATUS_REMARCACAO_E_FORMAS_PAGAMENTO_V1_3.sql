/* VIVER BEM SAUDE - SCRIPT 06 - PROCEDURES DE STATUS, PAGAMENTO E REMARCACAO (BLOCO 4 DA API) E FORMAS DE PAGAMENTO BASICAS
   EXECUTAR DEPOIS DOS SCRIPTS 01, 02, 03 E 05, NO BANCO VBSAGENDA. PODE SER EXECUTADO MAIS DE UMA VEZ:
   AS PROCEDURES USAM CREATE OR ALTER E A CARGA DAS FORMAS DE PAGAMENTO SO INCLUI O QUE AINDA NAO EXISTE.

   REGRAS APLICADAS (PROJETO V2.19): RN05/RN30 (FLUXO DE STATUS), RN06 (CANCELAMENTO, FALTA E REMARCACAO),
   RN08 (AVISO A RECEPCAO NA LISTA DE ESPERA), RN09 (SEM SOBREPOSICAO), RN17 (PAGAMENTO NA CHEGADA), RN31 (ENCAIXE).

   CODIGOS DE ERRO (50001 A 50005 JA EXISTEM NO SCRIPT 02):
   50001 AGENDA EM USO POR OUTRA OPERACAO       50002 HORARIO INDISPONIVEL (RN09)
   50003 LIMITE DE ENCAIXES DO DIA              50004 CONSULTA ALTERADA POR OUTRO USUARIO (VERSAO)
   50005 CONSULTA INEXISTENTE
   50006 STATUS INFORMADO INVALIDO              50007 MUDANCA FORA DO FLUXO DE STATUS
   50008 MOTIVO (OU QUEM CANCELOU) OBRIGATORIO  50009 CANCELAMENTO PELO PACIENTE FORA DO PRAZO
   50010 FALTA ANTES DO HORARIO DA CONSULTA     50011 CHECK-IN SEM PAGAMENTO CONFIRMADO
   50012 PAGAMENTO JA CONFIRMADO                50013 CONSULTA NAO PODE SER REMARCADA NESTE STATUS */

/* ================== 1. FORMAS DE PAGAMENTO BASICAS (RN17) ================== */
INSERT INTO DBO.[FORMA_PAGAMENTO] ([DESCRICAO], [TIPO], [CONDICAO])
SELECT V.[DESCRICAO], V.[TIPO], V.[CONDICAO]
FROM (VALUES
    (N'Dinheiro',          N'DINHEIRO',       N'A_VISTA'),
    (N'PIX',               N'PIX',            N'A_VISTA'),
    (N'Cartão de crédito', N'CARTAO_CREDITO', N'A_VISTA'),
    (N'Cartão de débito',  N'CARTAO_DEBITO',  N'A_VISTA')) AS V ([DESCRICAO], [TIPO], [CONDICAO])
WHERE NOT EXISTS (SELECT 1 FROM DBO.[FORMA_PAGAMENTO] AS F WHERE F.[DESCRICAO] = V.[DESCRICAO]);
/* A FORMA DO TIPO CONVENIO E CRIADA PELA APLICACAO A CADA CONVENIO CADASTRADO (F7). */
GO

/* ================== 2. MUDANCA DE STATUS (RN30) ==================
   FLUXO: AGENDADA -> CONFIRMADA, CANCELADA, FALTA | CONFIRMADA -> CHECK_IN, CANCELADA, FALTA
          CHECK_IN -> EM_ATENDIMENTO, CANCELADA | EM_ATENDIMENTO -> CONCLUIDA.
   REMARCADA NAO E INFORMADA AQUI: RESULTA DA PROCEDURE USP_CONSULTA_REMARCAR. */
CREATE OR ALTER PROCEDURE DBO.USP_CONSULTA_ALTERAR_STATUS
    @CODIGO_CONSULTA INT, @STATUS_NOVO NVARCHAR(20), @MOTIVO NVARCHAR(500) = NULL,
    @CANCELADO_POR NVARCHAR(10) = NULL, @VERSAO BINARY(8), @CODIGO_USUARIO INT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @STATUS_NOVO NOT IN ('CONFIRMADA', 'CHECK_IN', 'EM_ATENDIMENTO', 'CONCLUIDA', 'CANCELADA', 'FALTA')
        THROW 50006, 'Status informado inválido.', 1;

    BEGIN TRANSACTION;

    DECLARE @STATUS NVARCHAR(20), @VERS BINARY(8), @INICIO DATETIME2(0), @PAGAMENTO BIT;
    DECLARE @PROFISSIONAL INT, @ESPECIALIDADE INT, @UNIDADE INT;
    SELECT @STATUS = [STATUS], @VERS = [VERSAO], @INICIO = [DATA_INICIO], @PAGAMENTO = [PAGAMENTO_CONFIRMADO],
           @PROFISSIONAL = [CODIGO_PROFISSIONAL], @ESPECIALIDADE = [CODIGO_ESPECIALIDADE], @UNIDADE = [CODIGO_UNIDADE]
    FROM DBO.[CONSULTA] WITH (UPDLOCK, ROWLOCK)
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    IF @STATUS IS NULL THROW 50005, 'Consulta inexistente.', 1;
    IF @VERS <> @VERSAO THROW 50004, 'A consulta foi alterada por outro usuário. Recarregue e tente novamente.', 1;

    IF NOT (   (@STATUS = 'AGENDADA'       AND @STATUS_NOVO IN ('CONFIRMADA', 'CANCELADA', 'FALTA'))
            OR (@STATUS = 'CONFIRMADA'     AND @STATUS_NOVO IN ('CHECK_IN', 'CANCELADA', 'FALTA'))
            OR (@STATUS = 'CHECK_IN'       AND @STATUS_NOVO IN ('EM_ATENDIMENTO', 'CANCELADA'))
            OR (@STATUS = 'EM_ATENDIMENTO' AND @STATUS_NOVO = 'CONCLUIDA'))
        THROW 50007, 'Mudança de status não permitida pelo fluxo da consulta.', 1;

    IF @STATUS_NOVO IN ('CANCELADA', 'FALTA') AND NULLIF(LTRIM(RTRIM(@MOTIVO)), '') IS NULL
        THROW 50008, 'O motivo é obrigatório no cancelamento e na falta.', 1;
    IF @STATUS_NOVO = 'CANCELADA' AND @CANCELADO_POR IS NULL
        THROW 50008, 'Informe quem cancelou a consulta (paciente ou clínica).', 1;

    IF @STATUS_NOVO = 'CANCELADA' AND @CANCELADO_POR = 'PACIENTE'
    BEGIN
        /* ANTECEDENCIA MINIMA PARA O PACIENTE CANCELAR (RN06). A CLINICA CANCELA A QUALQUER MOMENTO. */
        DECLARE @PRAZO_H INT = ISNULL(TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'ANTECEDENCIA_CANCELAMENTO_H')), 48);
        IF DATEDIFF(MINUTE, SYSUTCDATETIME(), @INICIO) < @PRAZO_H * 60
            THROW 50009, 'Cancelamento pelo paciente fora do prazo mínimo de antecedência.', 1;
    END;

    IF @STATUS_NOVO = 'FALTA' AND SYSUTCDATETIME() < @INICIO
        THROW 50010, 'A falta só pode ser registrada depois do horário da consulta.', 1;

    IF @STATUS_NOVO = 'CHECK_IN' AND @PAGAMENTO = 0
        THROW 50011, 'Confirme o pagamento antes de fazer o check-in (RN17).', 1;

    UPDATE DBO.[CONSULTA]
    SET [STATUS] = @STATUS_NOVO, [DATA_ATUALIZACAO] = SYSUTCDATETIME()
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    INSERT INTO DBO.[CONSULTA_STATUS_HISTORICO] ([CODIGO_CONSULTA], [STATUS_ANTERIOR], [STATUS_NOVO], [MOTIVO], [CANCELADO_POR], [CODIGO_USUARIO])
    VALUES (@CODIGO_CONSULTA, @STATUS, @STATUS_NOVO, NULLIF(LTRIM(RTRIM(@MOTIVO)), ''),
            CASE WHEN @STATUS_NOVO = 'CANCELADA' THEN @CANCELADO_POR END, @CODIGO_USUARIO);

    /* RN08: HORARIO LIBERADO. SE HA PACIENTE AGUARDANDO NESSE PROFISSIONAL OU ESPECIALIDADE, AVISA A RECEPCAO
       (CODIGO_USUARIO_DESTINO NULO = TODA A RECEPCAO) E MARCA OS ITENS COMO NOTIFICADO. */
    IF @STATUS_NOVO = 'CANCELADA'
       AND EXISTS (SELECT 1 FROM DBO.[LISTA_ESPERA]
                   WHERE [STATUS] = 'AGUARDANDO'
                     AND ([CODIGO_PROFISSIONAL] = @PROFISSIONAL OR ([CODIGO_PROFISSIONAL] IS NULL AND [CODIGO_ESPECIALIDADE] = @ESPECIALIDADE))
                     AND ([CODIGO_UNIDADE] IS NULL OR [CODIGO_UNIDADE] = @UNIDADE))
    BEGIN
        /* HORARIO DE BRASILIA = UTC - 3 (SEM HORARIO DE VERAO DESDE 2019). */
        DECLARE @LOCAL DATETIME2(0) = DATEADD(HOUR, -3, @INICIO);
        DECLARE @MSG NVARCHAR(500) = N'Horário liberado em ' + CONVERT(NVARCHAR(10), @LOCAL, 103) + N' às ' + CONVERT(NVARCHAR(5), @LOCAL, 108)
                                   + N'. Há paciente na lista de espera para este profissional ou especialidade.';
        INSERT INTO DBO.[NOTIFICACAO_INTERNA] ([TIPO], [CODIGO_CONSULTA], [CODIGO_USUARIO_DESTINO], [MENSAGEM])
        VALUES ('HORARIO_DISPONIVEL', @CODIGO_CONSULTA, NULL, @MSG);

        UPDATE DBO.[LISTA_ESPERA]
        SET [STATUS] = 'NOTIFICADO', [DATA_NOTIFICACAO] = SYSUTCDATETIME()
        WHERE [STATUS] = 'AGUARDANDO'
          AND ([CODIGO_PROFISSIONAL] = @PROFISSIONAL OR ([CODIGO_PROFISSIONAL] IS NULL AND [CODIGO_ESPECIALIDADE] = @ESPECIALIDADE))
          AND ([CODIGO_UNIDADE] IS NULL OR [CODIGO_UNIDADE] = @UNIDADE);
    END;

    COMMIT TRANSACTION;
END;
GO

/* ================== 3. CONFIRMACAO DO PAGAMENTO (RN17) ==================
   FEITA PELA RECEPCAO NA CHEGADA DO PACIENTE, ANTES DO CHECK-IN. PODE TROCAR A FORMA DE PAGAMENTO.
   A COERENCIA ENTRE FORMA DO TIPO CONVENIO E O CONVENIO DA CONSULTA E CONFERIDA PELA APLICACAO. */
CREATE OR ALTER PROCEDURE DBO.USP_CONSULTA_CONFIRMAR_PAGAMENTO
    @CODIGO_CONSULTA INT, @CODIGO_PAGAMENTO INT = NULL, @VERSAO BINARY(8), @CODIGO_USUARIO INT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    BEGIN TRANSACTION;

    DECLARE @STATUS NVARCHAR(20), @VERS BINARY(8), @PAGAMENTO BIT;
    SELECT @STATUS = [STATUS], @VERS = [VERSAO], @PAGAMENTO = [PAGAMENTO_CONFIRMADO]
    FROM DBO.[CONSULTA] WITH (UPDLOCK, ROWLOCK)
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    IF @STATUS IS NULL THROW 50005, 'Consulta inexistente.', 1;
    IF @VERS <> @VERSAO THROW 50004, 'A consulta foi alterada por outro usuário. Recarregue e tente novamente.', 1;
    IF @STATUS NOT IN ('AGENDADA', 'CONFIRMADA', 'CHECK_IN', 'EM_ATENDIMENTO')
        THROW 50007, 'Consulta em status que não permite confirmar o pagamento.', 1;
    IF @PAGAMENTO = 1 THROW 50012, 'O pagamento desta consulta já foi confirmado.', 1;

    UPDATE DBO.[CONSULTA]
    SET [PAGAMENTO_CONFIRMADO] = 1, [DATA_PAGAMENTO] = SYSUTCDATETIME(), [PAGAMENTO_CONFIRMADO_USUARIO] = @CODIGO_USUARIO,
        [CODIGO_PAGAMENTO] = ISNULL(@CODIGO_PAGAMENTO, [CODIGO_PAGAMENTO]), [DATA_ATUALIZACAO] = SYSUTCDATETIME()
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    COMMIT TRANSACTION;
END;
GO

/* ================== 4. REMARCACAO (RN06, G5) ==================
   CRIA UMA NOVA CONSULTA VINCULADA A ORIGINAL E MARCA A ORIGINAL COMO REMARCADA, NA MESMA TRANSACAO.
   O PAGAMENTO JA CONFIRMADO SEGUE PARA A NOVA CONSULTA. O LINK ONLINE NAO E COPIADO: A APLICACAO GERA UM NOVO.
   A ORIGINAL E MARCADA ANTES DA CONFERENCIA DE SOBREPOSICAO, PARA NAO CONFLITAR COM ELA MESMA (EX.: MOVER 15 MINUTOS).
   QUALQUER ERRO DESFAZ TUDO. AS AGENDAS DOS DOIS PROFISSIONAIS SAO RESERVADAS EM ORDEM CRESCENTE DE CODIGO
   (EVITA IMPASSE ENTRE DUAS REMARCACOES SIMULTANEAS). */
CREATE OR ALTER PROCEDURE DBO.USP_CONSULTA_REMARCAR
    @CODIGO_CONSULTA INT, @NOVO_INICIO DATETIME2(0), @NOVO_FIM DATETIME2(0) = NULL, @MOTIVO NVARCHAR(500),
    @CODIGO_PROFISSIONAL INT = NULL, @CODIGO_ESPECIALIDADE INT = NULL, @CODIGO_UNIDADE INT = NULL, @CODIGO_SALA INT = NULL,
    @ENCAIXE BIT = 0, @VERSAO BINARY(8), @CODIGO_USUARIO INT,
    @CODIGO_CONSULTA_NOVA INT OUTPUT, @CODIGO_PUBLIC UNIQUEIDENTIFIER OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF NULLIF(LTRIM(RTRIM(@MOTIVO)), '') IS NULL THROW 50008, 'O motivo é obrigatório na remarcação.', 1;
    IF @NOVO_FIM IS NULL
        SET @NOVO_FIM = DATEADD(MINUTE, ISNULL(TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'DURACAO_PADRAO_CONSULTA_MIN')), 45), @NOVO_INICIO);

    BEGIN TRANSACTION;

    DECLARE @PACIENTE INT, @PROF_ORIG INT, @ESP_ORIG INT, @UNI_ORIG INT, @SALA_ORIG INT, @MODALIDADE NVARCHAR(10), @TIPO NVARCHAR(10);
    DECLARE @CONVENIO INT, @CARTEIRINHA NVARCHAR(30), @VALOR DECIMAL(10,2), @FORMA INT, @PAG BIT, @DATA_PAG DATETIME2(0), @PAG_USUARIO INT;
    DECLARE @STATUS NVARCHAR(20), @VERS BINARY(8);
    SELECT @PACIENTE = [CODIGO_PACIENTE], @PROF_ORIG = [CODIGO_PROFISSIONAL], @ESP_ORIG = [CODIGO_ESPECIALIDADE], @UNI_ORIG = [CODIGO_UNIDADE],
           @SALA_ORIG = [CODIGO_SALA], @MODALIDADE = [MODALIDADE], @TIPO = [TIPO_ATENDIMENTO], @CONVENIO = [CODIGO_CONVENIO],
           @CARTEIRINHA = [NUMERO_CARTEIRINHA], @VALOR = [VALOR], @FORMA = [CODIGO_PAGAMENTO], @PAG = [PAGAMENTO_CONFIRMADO],
           @DATA_PAG = [DATA_PAGAMENTO], @PAG_USUARIO = [PAGAMENTO_CONFIRMADO_USUARIO], @STATUS = [STATUS], @VERS = [VERSAO]
    FROM DBO.[CONSULTA] WITH (UPDLOCK, ROWLOCK)
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    IF @STATUS IS NULL THROW 50005, 'Consulta inexistente.', 1;
    IF @VERS <> @VERSAO THROW 50004, 'A consulta foi alterada por outro usuário. Recarregue e tente novamente.', 1;
    IF @STATUS NOT IN ('AGENDADA', 'CONFIRMADA')
        THROW 50013, 'Só é possível remarcar consulta agendada ou confirmada.', 1;

    DECLARE @PROF_NOVO INT = ISNULL(@CODIGO_PROFISSIONAL, @PROF_ORIG);
    DECLARE @ESP_NOVA  INT = ISNULL(@CODIGO_ESPECIALIDADE, @ESP_ORIG);
    DECLARE @UNI_NOVA  INT = ISNULL(@CODIGO_UNIDADE, @UNI_ORIG);
    /* SALA: SEM UNIDADE NEM SALA INFORMADAS, MANTEM A ORIGINAL; SE TROCAR DE UNIDADE, A APLICACAO INFORMA A NOVA SALA. */
    DECLARE @SALA_NOVA INT = CASE WHEN @CODIGO_UNIDADE IS NULL AND @CODIGO_SALA IS NULL THEN @SALA_ORIG ELSE @CODIGO_SALA END;

    /* RESERVA DAS AGENDAS EM ORDEM CRESCENTE DE PROFISSIONAL. */
    DECLARE @P1 INT = CASE WHEN @PROF_NOVO < @PROF_ORIG THEN @PROF_NOVO ELSE @PROF_ORIG END;
    DECLARE @P2 INT = CASE WHEN @PROF_NOVO < @PROF_ORIG THEN @PROF_ORIG ELSE @PROF_NOVO END;
    DECLARE @RECURSO NVARCHAR(100), @R INT;
    SET @RECURSO = N'AGENDA_PROFISSIONAL_' + CONVERT(NVARCHAR(10), @P1);
    EXEC @R = SP_GETAPPLOCK @RESOURCE = @RECURSO, @LOCKMODE = 'EXCLUSIVE', @LOCKOWNER = 'TRANSACTION', @LOCKTIMEOUT = 10000;
    IF @R < 0 THROW 50001, 'Agenda do profissional em uso por outra operação. Tente novamente.', 1;
    IF @P2 <> @P1
    BEGIN
        SET @RECURSO = N'AGENDA_PROFISSIONAL_' + CONVERT(NVARCHAR(10), @P2);
        EXEC @R = SP_GETAPPLOCK @RESOURCE = @RECURSO, @LOCKMODE = 'EXCLUSIVE', @LOCKOWNER = 'TRANSACTION', @LOCKTIMEOUT = 10000;
        IF @R < 0 THROW 50001, 'Agenda do profissional em uso por outra operação. Tente novamente.', 1;
    END;

    /* A ORIGINAL SAI DA AGENDA ANTES DA CONFERENCIA DE SOBREPOSICAO (REMARCADAS NAO CONTAM, RN09). */
    UPDATE DBO.[CONSULTA] SET [STATUS] = 'REMARCADA', [DATA_ATUALIZACAO] = SYSUTCDATETIME() WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;
    INSERT INTO DBO.[CONSULTA_STATUS_HISTORICO] ([CODIGO_CONSULTA], [STATUS_ANTERIOR], [STATUS_NOVO], [MOTIVO], [CODIGO_USUARIO])
    VALUES (@CODIGO_CONSULTA, @STATUS, 'REMARCADA', LTRIM(RTRIM(@MOTIVO)), @CODIGO_USUARIO);

    IF EXISTS (SELECT 1 FROM DBO.[CONSULTA] WITH (UPDLOCK, HOLDLOCK)
               WHERE [CODIGO_PROFISSIONAL] = @PROF_NOVO
                 AND [STATUS] NOT IN ('CANCELADA', 'REMARCADA')
                 AND [DATA_INICIO] < @NOVO_FIM AND [DATA_FIM] > @NOVO_INICIO)
        THROW 50002, 'Horário indisponível: o profissional já tem consulta nesse intervalo (RN09).', 1;

    IF @ENCAIXE = 1
    BEGIN
        DECLARE @LIM INT = TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'LIMITE_ENCAIXES_DIA'));
        IF @LIM IS NOT NULL AND (SELECT COUNT(*) FROM DBO.[CONSULTA]
                                 WHERE [CODIGO_PROFISSIONAL] = @PROF_NOVO AND [ENCAIXE] = 1
                                   AND [STATUS] NOT IN ('CANCELADA', 'REMARCADA')
                                   AND CONVERT(DATE, [DATA_INICIO]) = CONVERT(DATE, @NOVO_INICIO)) >= @LIM
            THROW 50003, 'Limite de encaixes do dia atingido.', 1;
    END;

    INSERT INTO DBO.[CONSULTA] ([CODIGO_PACIENTE], [CODIGO_PROFISSIONAL], [CODIGO_ESPECIALIDADE], [CODIGO_UNIDADE], [CODIGO_SALA], [MODALIDADE], [LINK_ONLINE],
        [TIPO_ATENDIMENTO], [CODIGO_CONVENIO], [NUMERO_CARTEIRINHA], [DATA_INICIO], [DATA_FIM], [VALOR], [CODIGO_PAGAMENTO], [PAGAMENTO_CONFIRMADO],
        [DATA_PAGAMENTO], [PAGAMENTO_CONFIRMADO_USUARIO], [STATUS], [CODIGO_CONSULTA_ORIGEM], [ENCAIXE], [CRIACAO_USUARIO])
    VALUES (@PACIENTE, @PROF_NOVO, @ESP_NOVA, @UNI_NOVA, @SALA_NOVA, @MODALIDADE, NULL,
        @TIPO, @CONVENIO, @CARTEIRINHA, @NOVO_INICIO, @NOVO_FIM, @VALOR, @FORMA, @PAG,
        @DATA_PAG, @PAG_USUARIO, 'AGENDADA', @CODIGO_CONSULTA, @ENCAIXE, @CODIGO_USUARIO);

    SET @CODIGO_CONSULTA_NOVA = SCOPE_IDENTITY();
    SELECT @CODIGO_PUBLIC = [CODIGO_PUBLIC] FROM DBO.[CONSULTA] WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA_NOVA;

    INSERT INTO DBO.[CONSULTA_STATUS_HISTORICO] ([CODIGO_CONSULTA], [STATUS_ANTERIOR], [STATUS_NOVO], [CODIGO_USUARIO])
    VALUES (@CODIGO_CONSULTA_NOVA, NULL, 'AGENDADA', @CODIGO_USUARIO);

    COMMIT TRANSACTION;
END;
GO

