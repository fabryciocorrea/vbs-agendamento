GRANT EXECUTE ON DBO.USP_CONSULTA_ALTERAR_STATUS      TO ROLE_APP_AGENDAMENTO;
GRANT EXECUTE ON DBO.USP_CONSULTA_CONFIRMAR_PAGAMENTO TO ROLE_APP_AGENDAMENTO;
GRANT EXECUTE ON DBO.USP_CONSULTA_REMARCAR            TO ROLE_APP_AGENDAMENTO;
GO

