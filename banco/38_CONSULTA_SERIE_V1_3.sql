USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.CONSULTA', 'CODIGO_SERIE') IS NULL
    ALTER TABLE DBO.[CONSULTA] ADD [CODIGO_SERIE] UNIQUEIDENTIFIER NULL;
GO

IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE NAME = 'IX_CONSULTA_SERIE' AND OBJECT_ID = OBJECT_ID('DBO.CONSULTA'))
    CREATE INDEX IX_CONSULTA_SERIE ON DBO.[CONSULTA] ([CODIGO_SERIE], [DATA_INICIO]) WHERE [CODIGO_SERIE] IS NOT NULL;
GO

GRANT UPDATE ON DBO.[CONSULTA] ([CODIGO_SERIE]) TO ROLE_APP_AGENDAMENTO;
GO

