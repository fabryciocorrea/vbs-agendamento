-- =====================================================================
-- SCRIPT 21 - VALOR DA CONSULTA NO CREDENCIAMENTO DO CONVENIO (V1.3)
-- O VALOR DA CONSULTA POR CONVENIO PASSA A FICAR NO CREDENCIAMENTO (CONVENIO + UNIDADE + ESPECIALIDADE).
-- NOVA COLUNA DBO.CREDENCIAMENTO_CONVENIO.VALOR. OS CREDENCIAMENTOS JA CADASTRADOS RECEBEM O VALOR QUE O CONVENIO TINHA
-- (DBO.CONVENIO.VALOR_CONSULTA, DO SCRIPT 19, QUE DEIXA DE SER USADA PELA APLICACAO).
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.CREDENCIAMENTO_CONVENIO', 'VALOR') IS NULL
    ALTER TABLE DBO.CREDENCIAMENTO_CONVENIO ADD [VALOR] DECIMAL(10,2) NOT NULL
        CONSTRAINT DF_CREDENCIAMENTO_CONVENIO_VALOR DEFAULT (0);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_CREDENCIAMENTO_CONVENIO_VALOR')
    ALTER TABLE DBO.CREDENCIAMENTO_CONVENIO ADD CONSTRAINT CK_CREDENCIAMENTO_CONVENIO_VALOR CHECK ([VALOR] >= 0);
GO

-- COPIA O VALOR ANTIGO DO CONVENIO PARA OS CREDENCIAMENTOS AINDA SEM VALOR.
IF COL_LENGTH('DBO.CONVENIO', 'VALOR_CONSULTA') IS NOT NULL
    EXEC (N'UPDATE K SET K.VALOR = C.VALOR_CONSULTA
            FROM DBO.CREDENCIAMENTO_CONVENIO K JOIN DBO.CONVENIO C ON C.CODIGO_CONVENIO = K.CODIGO_CONVENIO
            WHERE K.VALOR = 0 AND C.VALOR_CONSULTA > 0;');
GO

SELECT K.CODIGO_CREDENCIAMENTO, C.RAZAO_SOCIAL, U.NOME_FANTASIA AS UNIDADE, E.NOME AS ESPECIALIDADE, K.SITUACAO, K.VALOR
FROM DBO.CREDENCIAMENTO_CONVENIO K
JOIN DBO.CONVENIO C ON C.CODIGO_CONVENIO = K.CODIGO_CONVENIO
JOIN DBO.UNIDADE U ON U.CODIGO_UNIDADE = K.CODIGO_UNIDADE
JOIN DBO.ESPECIALIDADE E ON E.CODIGO_ESPECIALIDADE = K.CODIGO_ESPECIALIDADE
ORDER BY C.RAZAO_SOCIAL, U.NOME_FANTASIA, E.NOME;
GO
