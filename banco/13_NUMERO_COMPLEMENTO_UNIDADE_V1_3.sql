-- =====================================================================
-- SCRIPT 13 - NUMERO E COMPLEMENTO DO ENDERECO DA UNIDADE (V1.3)
-- NUMERO: OBRIGATORIO (ATE 10 CARACTERES). SEM NUMERO = 'S/N'.
-- COMPLEMENTO: OPCIONAL (ATE 60 CARACTERES).
-- LINHAS EXISTENTES RECEBEM 'S/N'. PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.UNIDADE', 'NUMERO') IS NULL
    ALTER TABLE DBO.UNIDADE ADD [NUMERO] NVARCHAR(10) NOT NULL CONSTRAINT DF_UNIDADE_NUMERO DEFAULT 'S/N';
IF COL_LENGTH('DBO.UNIDADE', 'COMPLEMENTO') IS NULL
    ALTER TABLE DBO.UNIDADE ADD [COMPLEMENTO] NVARCHAR(60) NULL;
GO
IF EXISTS (SELECT 1 FROM SYS.DEFAULT_CONSTRAINTS WHERE NAME = 'DF_UNIDADE_NUMERO')
    ALTER TABLE DBO.UNIDADE DROP CONSTRAINT DF_UNIDADE_NUMERO;
GO

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'UNIDADE' AND COLUMN_NAME IN ('NUMERO', 'COMPLEMENTO');
GO
