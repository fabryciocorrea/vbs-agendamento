-- =====================================================================
-- SCRIPT 30 - GUIA CANCELADA (V1.3)
-- 1) NOVA SITUACAO DE GUIA: CANCELADA (CK_CONSULTA_GUIA_STATUS).
-- 2) USP_CONSULTA_ALTERAR_STATUS RECRIADA: CONSULTA POR CONVENIO CANCELADA CANCELA A GUIA AUTOMATICAMENTE
--    (E DESFAZ A CONFIRMACAO DE PAGAMENTO) QUANDO A GUIA NAO ESTA AUTORIZADA. SUBSTITUI O SCRIPT 27.
--    GUIA JA AUTORIZADA IMPEDE O CANCELAMENTO DA CONSULTA (ERRO 50016): O FATURAMENTO CANCELA A GUIA NO CONVENIO PRIMEIRO.
--    O ADMINISTRADOR PODE LIBERAR COM JUSTIFICATIVA; NESSE CASO A GUIA CONTINUA AUTORIZADA NA TELA DO FATURAMENTO ATE SER CANCELADA.
-- 3) AJUSTE DOS DADOS JA EXISTENTES: CONSULTAS DE CONVENIO CANCELADAS, COM GUIA NAO AUTORIZADA, PASSAM A TER GUIA CANCELADA.
-- GUIA AUTORIZADA SO PODE SER CANCELADA (PELO FATURAMENTO, EX.: PACIENTE FALTOU OU CANCELOU). PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_CONSULTA_GUIA_STATUS')
    ALTER TABLE DBO.CONSULTA DROP CONSTRAINT CK_CONSULTA_GUIA_STATUS;
GO
ALTER TABLE DBO.CONSULTA ADD CONSTRAINT CK_CONSULTA_GUIA_STATUS
    CHECK ([GUIA_STATUS] IS NULL OR [GUIA_STATUS] IN ('PENDENTE', 'AUTORIZADA', 'NEGADA', 'CANCELADA'));
GO

CREATE OR ALTER PROCEDURE DBO.USP_CONSULTA_ALTERAR_STATUS
    @CODIGO_CONSULTA INT, @STATUS_NOVO NVARCHAR(20), @MOTIVO NVARCHAR(500) = NULL,
    @CANCELADO_POR NVARCHAR(10) = NULL, @VERSAO BINARY(8), @CODIGO_USUARIO INT,
    @LIBERADO BIT = 0, @LIBERACAO_JUSTIFICATIVA NVARCHAR(500) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @STATUS_NOVO NOT IN ('CONFIRMADA', 'CHECK_IN', 'EM_ATENDIMENTO', 'CONCLUIDA', 'CANCELADA', 'FALTA')
        THROW 50006, 'Status informado inválido.', 1;

    BEGIN TRANSACTION;

    DECLARE @STATUS NVARCHAR(20), @VERS BINARY(8), @INICIO DATETIME2(0), @PAGAMENTO BIT, @TIPO NVARCHAR(10), @GUIA NVARCHAR(10);
    DECLARE @PROFISSIONAL INT, @ESPECIALIDADE INT, @UNIDADE INT;
    SELECT @STATUS = [STATUS], @VERS = [VERSAO], @INICIO = [DATA_INICIO], @PAGAMENTO = [PAGAMENTO_CONFIRMADO], @TIPO = [TIPO_ATENDIMENTO],
           @GUIA = ISNULL([GUIA_STATUS], 'PENDENTE'), @PROFISSIONAL = [CODIGO_PROFISSIONAL], @ESPECIALIDADE = [CODIGO_ESPECIALIDADE], @UNIDADE = [CODIGO_UNIDADE]
    FROM DBO.[CONSULTA] WITH (UPDLOCK, ROWLOCK)
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    IF @STATUS IS NULL THROW 50005, 'Consulta inexistente.', 1;
    IF @VERS <> @VERSAO THROW 50004, 'A consulta foi alterada por outro usuário. Recarregue e tente novamente.', 1;

    IF NOT (   (@STATUS = 'AGENDADA'       AND @STATUS_NOVO IN ('CONFIRMADA', 'CANCELADA', 'FALTA'))
            OR (@STATUS = 'CONFIRMADA'     AND @STATUS_NOVO IN ('CHECK_IN', 'CANCELADA', 'FALTA'))
            OR (@STATUS = 'CHECK_IN'       AND @STATUS_NOVO IN ('EM_ATENDIMENTO', 'CANCELADA'))
            OR (@STATUS = 'EM_ATENDIMENTO' AND @STATUS_NOVO = 'CONCLUIDA')
            /* ATALHO: CONSULTA VENCIDA PODE SER CONCLUIDA DIRETO. */
            OR (@STATUS IN ('AGENDADA', 'CONFIRMADA', 'CHECK_IN') AND @STATUS_NOVO = 'CONCLUIDA')
            /* LIBERACAO DO ADMINISTRADOR: PULA ETAPAS DE UMA CONSULTA AINDA ATIVA. STATUS FINAIS (CONCLUIDA, CANCELADA, FALTA, REMARCADA) NAO MUDAM. */
            OR (@LIBERADO = 1 AND @STATUS IN ('AGENDADA', 'CONFIRMADA', 'CHECK_IN', 'EM_ATENDIMENTO') AND @STATUS_NOVO <> @STATUS))
        THROW 50007, 'Mudança de status não permitida pelo fluxo da consulta.', 1;

    IF @LIBERADO = 0 AND @STATUS_NOVO = 'CONCLUIDA' AND @STATUS <> 'EM_ATENDIMENTO' AND SYSUTCDATETIME() < @INICIO
        THROW 50014, 'A consulta só pode ser concluída diretamente depois do horário agendado.', 1;

    IF @STATUS_NOVO IN ('CANCELADA', 'FALTA') AND NULLIF(LTRIM(RTRIM(@MOTIVO)), '') IS NULL
        THROW 50008, 'O motivo é obrigatório no cancelamento e na falta.', 1;
    IF @STATUS_NOVO = 'CANCELADA' AND @CANCELADO_POR IS NULL
        THROW 50008, 'Informe quem cancelou a consulta (paciente ou clínica).', 1;

    IF @LIBERADO = 0 AND @STATUS_NOVO = 'CANCELADA' AND @CANCELADO_POR = 'PACIENTE'
    BEGIN
        /* ANTECEDENCIA MINIMA PARA O PACIENTE CANCELAR (RN06). A CLINICA CANCELA A QUALQUER MOMENTO. */
        DECLARE @PRAZO_H INT = ISNULL(TRY_CONVERT(INT, (SELECT [VALOR] FROM DBO.[PARAMETRO_SISTEMA] WHERE [CHAVE_PARAMETRO] = N'ANTECEDENCIA_CANCELAMENTO_H')), 48);
        IF DATEDIFF(MINUTE, SYSUTCDATETIME(), @INICIO) < @PRAZO_H * 60
            THROW 50009, 'Cancelamento pelo paciente fora do prazo mínimo de antecedência.', 1;
    END;

    IF @LIBERADO = 0 AND @STATUS_NOVO = 'FALTA' AND SYSUTCDATETIME() < @INICIO
        THROW 50010, 'A falta só pode ser registrada depois do horário da consulta.', 1;

    /* RN17: FLUXO DA RECEPCAO = CONFIRMA O AGENDAMENTO > CHECK-IN > CONFIRMA O PAGAMENTO > INICIA O ATENDIMENTO.
       O PAGAMENTO PARTICULAR PRECISA ESTAR CONFIRMADO PARA INICIAR O ATENDIMENTO. NO CONVENIO A GUIA E CONFIRMADA PELO FATURAMENTO. */
    IF @LIBERADO = 0 AND @STATUS_NOVO = 'EM_ATENDIMENTO' AND @PAGAMENTO = 0 AND @TIPO <> 'CONVENIO'
        THROW 50011, 'Confirme o pagamento antes de iniciar o atendimento (RN17).', 1;

    /* CONVENIO: O ATENDIMENTO SO COMECA (E A CONSULTA SO CONCLUI) COM A GUIA AUTORIZADA PELO FATURAMENTO. SEM EXCECAO. */
    IF @LIBERADO = 0 AND @STATUS_NOVO IN ('EM_ATENDIMENTO', 'CONCLUIDA') AND @TIPO = 'CONVENIO' AND @GUIA <> 'AUTORIZADA'
        THROW 50015, 'A guia do convênio precisa estar autorizada pelo faturamento para iniciar o atendimento.', 1;

    /* CONVENIO: GUIA AUTORIZADA EXISTE NO PLANO. O FATURAMENTO PRECISA CANCELAR A GUIA ANTES DE A CONSULTA SER CANCELADA. */
    IF @LIBERADO = 0 AND @STATUS_NOVO = 'CANCELADA' AND @TIPO = 'CONVENIO' AND @GUIA = 'AUTORIZADA'
        THROW 50016, 'A guia do convênio já foi autorizada. O faturamento precisa cancelar a guia antes de cancelar a consulta.', 1;

    UPDATE DBO.[CONSULTA]
    SET [STATUS] = @STATUS_NOVO, [DATA_ATUALIZACAO] = SYSUTCDATETIME(),
        [LIBERACAO_ADMIN_USUARIO] = CASE WHEN @LIBERADO = 1 THEN @CODIGO_USUARIO ELSE [LIBERACAO_ADMIN_USUARIO] END,
        [LIBERACAO_ADMIN_JUSTIFICATIVA] = CASE WHEN @LIBERADO = 1 THEN @LIBERACAO_JUSTIFICATIVA ELSE [LIBERACAO_ADMIN_JUSTIFICATIVA] END,
        [LIBERACAO_ADMIN_DATA] = CASE WHEN @LIBERADO = 1 THEN SYSUTCDATETIME() ELSE [LIBERACAO_ADMIN_DATA] END
    WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    /* CONVENIO: CONSULTA CANCELADA CANCELA A GUIA QUE AINDA NAO FOI AUTORIZADA. GUIA AUTORIZADA CONTINUA NA TELA DO FATURAMENTO ATE SER CANCELADA LA. */
    IF @STATUS_NOVO = 'CANCELADA' AND @TIPO = 'CONVENIO' AND @GUIA <> 'AUTORIZADA'
        UPDATE DBO.[CONSULTA]
        SET [GUIA_STATUS] = 'CANCELADA', [GUIA_DATA] = SYSUTCDATETIME(), [GUIA_USUARIO] = @CODIGO_USUARIO,
            [GUIA_OBSERVACAO] = LEFT(CONCAT(N'Consulta cancelada: ', NULLIF(LTRIM(RTRIM(@MOTIVO)), '')), 500),
            [PAGAMENTO_CONFIRMADO] = 0, [DATA_PAGAMENTO] = NULL, [PAGAMENTO_CONFIRMADO_USUARIO] = NULL
        WHERE [CODIGO_CONSULTA] = @CODIGO_CONSULTA;

    INSERT INTO DBO.[CONSULTA_STATUS_HISTORICO] ([CODIGO_CONSULTA], [STATUS_ANTERIOR], [STATUS_NOVO], [MOTIVO], [CANCELADO_POR], [CODIGO_USUARIO])
    VALUES (@CODIGO_CONSULTA, @STATUS, @STATUS_NOVO,
            CASE WHEN @LIBERADO = 1 THEN LEFT(CONCAT(NULLIF(LTRIM(RTRIM(@MOTIVO)), ''), CASE WHEN NULLIF(LTRIM(RTRIM(@MOTIVO)), '') IS NULL THEN N'' ELSE N' | ' END, N'Liberação do administrador: ', @LIBERACAO_JUSTIFICATIVA), 500)
                 ELSE NULLIF(LTRIM(RTRIM(@MOTIVO)), '') END,
            CASE WHEN @STATUS_NOVO = 'CANCELADA' THEN @CANCELADO_POR END, @CODIGO_USUARIO);

    /* RN08: HORARIO LIBERADO. SE HA PACIENTE AGUARDANDO NESSE PROFISSIONAL OU ESPECIALIDADE, AVISA A RECEPCAO
       (CODIGO_USUARIO_DESTINO NULO = TODA A RECEPCAO) E MARCA OS ITENS COMO NOTIFICADO. */
    IF @STATUS_NOVO = 'CANCELADA' AND @INICIO > SYSUTCDATETIME()
       AND EXISTS (SELECT 1 FROM DBO.[LISTA_ESPERA]
                   WHERE [STATUS] = 'AGUARDANDO'
                     AND ([CODIGO_PROFISSIONAL] = @PROFISSIONAL OR ([CODIGO_PROFISSIONAL] IS NULL AND [CODIGO_ESPECIALIDADE] = @ESPECIALIDADE))
                     AND ([CODIGO_UNIDADE] IS NULL OR [CODIGO_UNIDADE] = @UNIDADE))
    BEGIN
        /* HORARIO DE BRASILIA = UTC - 3 (SEM HORARIO DE VERAO DESDE 2019). */
        DECLARE @LOCAL DATETIME2(0) = DATEADD(HOUR, -3, @INICIO);
        DECLARE @MSG NVARCHAR(500) = N'Horário liberado em ' + CONVERT(NVARCHAR(10), @LOCAL, 103) + N' às ' + CONVERT(NVARCHAR(5), @LOCAL, 108)
                                   + N'. Há paciente na lista de espera para este profissional ou especialidade.';
        INSERT INTO DBO.[NOTIFICACAO_INTERNA] ([TIPO], [CODIGO_CONSULTA], [CODIGO_USUARIO_DESTINO], [MENSAGEM])
        VALUES ('HORARIO_DISPONIVEL', @CODIGO_CONSULTA, NULL, @MSG);

        UPDATE DBO.[LISTA_ESPERA]
        SET [STATUS] = 'NOTIFICADO', [DATA_NOTIFICACAO] = SYSUTCDATETIME()
        WHERE [STATUS] = 'AGUARDANDO'
          AND ([CODIGO_PROFISSIONAL] = @PROFISSIONAL OR ([CODIGO_PROFISSIONAL] IS NULL AND [CODIGO_ESPECIALIDADE] = @ESPECIALIDADE))
          AND ([CODIGO_UNIDADE] IS NULL OR [CODIGO_UNIDADE] = @UNIDADE);
    END;

    COMMIT TRANSACTION;
END;
GO


UPDATE DBO.CONSULTA
SET GUIA_STATUS = 'CANCELADA', GUIA_DATA = ISNULL(GUIA_DATA, SYSUTCDATETIME()),
    PAGAMENTO_CONFIRMADO = 0, DATA_PAGAMENTO = NULL, PAGAMENTO_CONFIRMADO_USUARIO = NULL
WHERE TIPO_ATENDIMENTO = 'CONVENIO' AND STATUS = 'CANCELADA' AND ISNULL(GUIA_STATUS, 'PENDENTE') IN ('PENDENTE', 'NEGADA');
GO

PRINT 'SCRIPT 30 EXECUTADO';
GO
