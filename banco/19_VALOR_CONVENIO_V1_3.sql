-- =====================================================================
-- SCRIPT 19 - VALOR DA CONSULTA NO CADASTRO DO CONVENIO (V1.3)
-- NOVA COLUNA DBO.CONVENIO.VALOR_CONSULTA (OBRIGATORIA). CONVENIOS JA CADASTRADOS FICAM COM 0,00
-- ATE QUE O VALOR SEJA INFORMADO NA TELA DE CONVENIOS. A CONSULTA POR CONVENIO USA ESTE VALOR.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.CONVENIO', 'VALOR_CONSULTA') IS NULL
    ALTER TABLE DBO.CONVENIO ADD [VALOR_CONSULTA] DECIMAL(10,2) NOT NULL
        CONSTRAINT DF_CONVENIO_VALOR_CONSULTA DEFAULT (0);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_CONVENIO_VALOR_CONSULTA')
    ALTER TABLE DBO.CONVENIO ADD CONSTRAINT CK_CONVENIO_VALOR_CONSULTA CHECK ([VALOR_CONSULTA] >= 0);
GO

SELECT CODIGO_CONVENIO, RAZAO_SOCIAL, VALOR_CONSULTA FROM DBO.CONVENIO;
GO
