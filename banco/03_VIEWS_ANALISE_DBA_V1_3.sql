/* =====================================================================
   VIVER BEM SAUDE - SCRIPT 03 - VIEWS PARA ANALISE DO DBA
   VERSAO 1.3 - 26/10/2026
   AS COLUNAS DE CODIGO CONTINUAM INTEIRAS NAS TABELAS (INTEGRIDADE E DESEMPENHO).
   ESTAS VIEWS MOSTRAM OS NOMES (USUARIO, PROFISSIONAL, PACIENTE ETC.) AO LADO DOS CODIGOS.
   NAO EXPOEM CPF NEM O TEXTO DO PRONTUARIO (DADOS CRIPTOGRAFADOS E SENSIVEIS).
   ===================================================================== */
SET NOCOUNT ON;
GO

CREATE OR ALTER VIEW DBO.VW_USUARIO AS
SELECT U.CODIGO_USUARIO, U.NOME_USUARIO AS LOGIN, U.NOME_COMPLETO AS USUARIO, U.EMAIL, U.CARGO, U.ATIVO,
       U.CODIGO_PERFIL, PE.NOME AS PERFIL,
       U.CODIGO_PROFISSIONAL, PR.NOME AS PROFISSIONAL,
       U.TENTATIVAS_FALHAS, U.DATA_BLOQUEIO, U.DATA_ULTIMO_LOGIN, U.DATA_CRIACAO, U.DATA_ATUALIZACAO,
       U.CRIACAO_USUARIO, UC.NOME_COMPLETO AS CRIADO_POR,
       U.ATUALIZACAO_USUARIO, UA.NOME_COMPLETO AS ATUALIZADO_POR
FROM DBO.USUARIO U
JOIN DBO.PERFIL_ACESSO PE ON PE.CODIGO_PERFIL = U.CODIGO_PERFIL
LEFT JOIN DBO.PROFISSIONAL PR ON PR.CODIGO_PROFISSIONAL = U.CODIGO_PROFISSIONAL
LEFT JOIN DBO.USUARIO UC ON UC.CODIGO_USUARIO = U.CRIACAO_USUARIO
LEFT JOIN DBO.USUARIO UA ON UA.CODIGO_USUARIO = U.ATUALIZACAO_USUARIO;
GO

CREATE OR ALTER VIEW DBO.VW_PACIENTE AS
SELECT P.CODIGO_PACIENTE, P.CODIGO_PUBLIC, P.NOME AS PACIENTE, P.ATIVO, P.ESTRANGEIRO, P.DATA_NASCIMENTO,
       P.TELEFONE, P.EMAIL, P.CIDADE, P.UF,
       P.CODIGO_CONVENIO, CV.NOME_FANTASIA AS CONVENIO, P.NUMERO_CARTEIRINHA, P.DATA_VALIDADE_CARTEIRINHA,
       P.CODIGO_PROFISSIONAL_RESPONSAVEL, PR.NOME AS PROFISSIONAL_RESPONSAVEL,
       P.CODIGO_RESPONSAVEL_LEGAL, RL.NOME AS RESPONSAVEL_LEGAL,
       P.DATA_CRIACAO, P.DATA_ATUALIZACAO,
       P.CRIACAO_USUARIO, UC.NOME_COMPLETO AS CRIADO_POR,
       P.ATUALIZACAO_USUARIO, UA.NOME_COMPLETO AS ATUALIZADO_POR
FROM DBO.PACIENTE P
JOIN DBO.PROFISSIONAL PR ON PR.CODIGO_PROFISSIONAL = P.CODIGO_PROFISSIONAL_RESPONSAVEL
LEFT JOIN DBO.CONVENIO CV ON CV.CODIGO_CONVENIO = P.CODIGO_CONVENIO
LEFT JOIN DBO.RESPONSAVEL_LEGAL RL ON RL.CODIGO_RESPONSAVEL = P.CODIGO_RESPONSAVEL_LEGAL
LEFT JOIN DBO.USUARIO UC ON UC.CODIGO_USUARIO = P.CRIACAO_USUARIO
LEFT JOIN DBO.USUARIO UA ON UA.CODIGO_USUARIO = P.ATUALIZACAO_USUARIO;
GO

CREATE OR ALTER VIEW DBO.VW_CONSULTA AS
SELECT C.CODIGO_CONSULTA, C.CODIGO_PUBLIC, C.STATUS, C.ENCAIXE, C.MODALIDADE, C.TIPO_ATENDIMENTO,
       C.DATA_INICIO, C.DATA_FIM,
       C.CODIGO_PACIENTE, P.NOME AS PACIENTE,
       C.CODIGO_PROFISSIONAL, PR.NOME AS PROFISSIONAL,
       C.CODIGO_ESPECIALIDADE, E.NOME AS ESPECIALIDADE,
       C.CODIGO_UNIDADE, U.NOME_FANTASIA AS UNIDADE,
       C.CODIGO_SALA, S.NUMERO AS SALA,
       C.CODIGO_CONVENIO, CV.NOME_FANTASIA AS CONVENIO, C.NUMERO_CARTEIRINHA,
       C.VALOR, C.CODIGO_PAGAMENTO, FP.DESCRICAO AS FORMA_PAGAMENTO,
       C.PAGAMENTO_CONFIRMADO, C.DATA_PAGAMENTO,
       C.PAGAMENTO_CONFIRMADO_USUARIO, UP.NOME_COMPLETO AS PAGAMENTO_CONFIRMADO_POR,
       C.CODIGO_CONSULTA_ORIGEM,
       C.CRIACAO_USUARIO, UC.NOME_COMPLETO AS CRIADO_POR,
       C.DATA_CRIACAO, C.DATA_ATUALIZACAO
FROM DBO.CONSULTA C
JOIN DBO.PACIENTE P ON P.CODIGO_PACIENTE = C.CODIGO_PACIENTE
JOIN DBO.PROFISSIONAL PR ON PR.CODIGO_PROFISSIONAL = C.CODIGO_PROFISSIONAL
JOIN DBO.ESPECIALIDADE E ON E.CODIGO_ESPECIALIDADE = C.CODIGO_ESPECIALIDADE
JOIN DBO.UNIDADE U ON U.CODIGO_UNIDADE = C.CODIGO_UNIDADE
JOIN DBO.FORMA_PAGAMENTO FP ON FP.CODIGO_PAGAMENTO = C.CODIGO_PAGAMENTO
LEFT JOIN DBO.SALA S ON S.CODIGO_SALA = C.CODIGO_SALA
LEFT JOIN DBO.CONVENIO CV ON CV.CODIGO_CONVENIO = C.CODIGO_CONVENIO
LEFT JOIN DBO.USUARIO UP ON UP.CODIGO_USUARIO = C.PAGAMENTO_CONFIRMADO_USUARIO
LEFT JOIN DBO.USUARIO UC ON UC.CODIGO_USUARIO = C.CRIACAO_USUARIO;
GO

CREATE OR ALTER VIEW DBO.VW_CONSULTA_STATUS_HISTORICO AS
SELECT H.CODIGO_CONS_HIST, H.CODIGO_CONSULTA, C.DATA_INICIO, P.NOME AS PACIENTE, PR.NOME AS PROFISSIONAL,
       H.STATUS_ANTERIOR, H.STATUS_NOVO, H.MOTIVO, H.CANCELADO_POR,
       H.CODIGO_USUARIO, U.NOME_COMPLETO AS USUARIO, H.CRIACAO_DATA_HORA
FROM DBO.CONSULTA_STATUS_HISTORICO H
JOIN DBO.CONSULTA C ON C.CODIGO_CONSULTA = H.CODIGO_CONSULTA
JOIN DBO.PACIENTE P ON P.CODIGO_PACIENTE = C.CODIGO_PACIENTE
JOIN DBO.PROFISSIONAL PR ON PR.CODIGO_PROFISSIONAL = C.CODIGO_PROFISSIONAL
LEFT JOIN DBO.USUARIO U ON U.CODIGO_USUARIO = H.CODIGO_USUARIO;
GO

CREATE OR ALTER VIEW DBO.VW_LOG_AUDITORIA AS
SELECT L.CODIGO_LOG, L.DATA_HORA, L.ACAO, L.ENTIDADE, L.CODIGO_ENTIDADE,
       L.CODIGO_USUARIO, U.NOME_COMPLETO AS USUARIO,
       L.CODIGO_PACIENTE, P.NOME AS PACIENTE, L.DETALHES, L.IP
FROM DBO.LOG_AUDITORIA L
LEFT JOIN DBO.USUARIO U ON U.CODIGO_USUARIO = L.CODIGO_USUARIO
LEFT JOIN DBO.PACIENTE P ON P.CODIGO_PACIENTE = L.CODIGO_PACIENTE;
GO

CREATE OR ALTER VIEW DBO.VW_PACIENTE_PROFISSIONAL_HISTORICO AS
SELECT H.CODIGO_HISTORICO, H.CODIGO_PACIENTE, P.NOME AS PACIENTE,
       H.CODIGO_PROFISSIONAL, PR.NOME AS PROFISSIONAL, H.DATA_INICIO, H.DATA_FIM,
       H.ALTERACAO_USUARIO AS CODIGO_USUARIO_ALTEROU, U.NOME_COMPLETO AS USUARIO_ALTEROU
FROM DBO.PACIENTE_PROFISSIONAL_HISTORICO H
JOIN DBO.PACIENTE P ON P.CODIGO_PACIENTE = H.CODIGO_PACIENTE
JOIN DBO.PROFISSIONAL PR ON PR.CODIGO_PROFISSIONAL = H.CODIGO_PROFISSIONAL
JOIN DBO.USUARIO U ON U.CODIGO_USUARIO = H.ALTERACAO_USUARIO;
GO

/* PRONTUARIO SEM O TEXTO CLINICO: SO QUEM, QUANDO E DE QUEM */
CREATE OR ALTER VIEW DBO.VW_REGISTRO_PRONTUARIO AS
SELECT R.CODIGO_REGS_PRNT, R.CODIGO_PUBLIC, R.DATA_HORA_REGS,
       R.CODIGO_PACIENTE, P.NOME AS PACIENTE, R.CODIGO_CONSULTA,
       R.CODIGO_PROFISSIONAL, R.NOME_PROFISSIONAL, R.REGISTRO_PROFISSIONAL, R.NUMERO_CONSELHO, R.UF_CONSELHO
FROM DBO.REGISTRO_PRONTUARIO R
JOIN DBO.PACIENTE P ON P.CODIGO_PACIENTE = R.CODIGO_PACIENTE;
GO

CREATE OR ALTER VIEW DBO.VW_PRONTUARIO_CORRECAO AS
SELECT C.CODIGO_PRNT_CORRECAO, C.DATA_HORA_CORRECAO, C.CODIGO_REGS_PRNT,
       R.CODIGO_PACIENTE, P.NOME AS PACIENTE, R.NOME_PROFISSIONAL,
       C.MOTIVO, C.AUTORIZADO_USUARIO, C.CORRECAO_USUARIO
FROM DBO.PRONTUARIO_CORRECAO C
JOIN DBO.REGISTRO_PRONTUARIO R ON R.CODIGO_REGS_PRNT = C.CODIGO_REGS_PRNT
JOIN DBO.PACIENTE P ON P.CODIGO_PACIENTE = R.CODIGO_PACIENTE;
GO

CREATE OR ALTER VIEW DBO.VW_PROFISSIONAL AS
SELECT PR.CODIGO_PROFISSIONAL, PR.NOME AS PROFISSIONAL, PR.ATIVO, PR.REGISTRO_PROFISSIONAL, PR.NUMERO_CONSELHO, PR.UF_CONSELHO,
       (SELECT STRING_AGG(E.NOME, ', ') FROM DBO.PROFISSIONAL_ESPECIALIDADE PE JOIN DBO.ESPECIALIDADE E ON E.CODIGO_ESPECIALIDADE = PE.CODIGO_ESPECIALIDADE
         WHERE PE.CODIGO_PROFISSIONAL = PR.CODIGO_PROFISSIONAL) AS ESPECIALIDADES,
       (SELECT STRING_AGG(U.NOME_FANTASIA, ', ') FROM DBO.PROFISSIONAL_UNIDADE PU JOIN DBO.UNIDADE U ON U.CODIGO_UNIDADE = PU.CODIGO_UNIDADE
         WHERE PU.CODIGO_PROFISSIONAL = PR.CODIGO_PROFISSIONAL) AS UNIDADES,
       PR.DATA_CRIACAO, PR.DATA_ATUALIZACAO,
       PR.CRIACAO_USUARIO, UC.NOME_COMPLETO AS CRIADO_POR,
       PR.ATUALIZACAO_USUARIO, UA.NOME_COMPLETO AS ATUALIZADO_POR
FROM DBO.PROFISSIONAL PR
LEFT JOIN DBO.USUARIO UC ON UC.CODIGO_USUARIO = PR.CRIACAO_USUARIO
LEFT JOIN DBO.USUARIO UA ON UA.CODIGO_USUARIO = PR.ATUALIZACAO_USUARIO;
GO

/* PERMISSOES: SO LEITURA DAS VIEWS PARA QUEM FAZ A ANALISE */
IF DATABASE_PRINCIPAL_ID('ROLE_DBA_ANALISE') IS NULL CREATE ROLE ROLE_DBA_ANALISE;
GO
GRANT SELECT ON DBO.VW_USUARIO TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_PACIENTE TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_CONSULTA TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_CONSULTA_STATUS_HISTORICO TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_LOG_AUDITORIA TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_PACIENTE_PROFISSIONAL_HISTORICO TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_REGISTRO_PRONTUARIO TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_PRONTUARIO_CORRECAO TO ROLE_DBA_ANALISE;
GRANT SELECT ON DBO.VW_PROFISSIONAL TO ROLE_DBA_ANALISE;
GO
