-- =====================================================================
-- SCRIPT 25 - UNIFICAR A TELA DE FATURAMENTO (V1.3)
-- A TELA FATURAMENTO_GUIAS (FATURAMENTO.GUIAS) FOI INCORPORADA A TELA FATURAMENTO (FATURAMENTO.FINANCEIRO).
-- 1) COPIA AS LIBERACOES DOS PERFIS DA TELA ANTIGA PARA A NOVA (SEM SOBRESCREVER O QUE JA EXISTE NA NOVA);
-- 2) REMOVE A TELA ANTIGA DO CATALOGO. EXECUTAR NO SSMS COM O USUARIO DONO DO BANCO (PRECISA DESLIGAR UM TRIGGER DE PROTECAO).
-- PRECISA RODAR DEPOIS DE INICIAR O SERVIDOR UMA VEZ COM A VERSAO NOVA (ELE CADASTRA A TELA NOVA). PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

DECLARE @GUIAS INT = (SELECT [ID_TELA_SISTEMA] FROM DBO.[TELA_SISTEMA] WHERE [CODIGO] = N'faturamento.guias');
DECLARE @FIN INT = (SELECT [ID_TELA_SISTEMA] FROM DBO.[TELA_SISTEMA] WHERE [CODIGO] = N'faturamento.financeiro');

IF @FIN IS NULL
    RAISERROR('INICIE O SERVIDOR (DOTNET RUN) COM A VERSAO NOVA ANTES DE EXECUTAR ESTE SCRIPT.', 16, 1);
ELSE IF @GUIAS IS NULL
    PRINT 'A TELA ANTIGA JA FOI REMOVIDA. NADA A FAZER.';
ELSE
BEGIN
    BEGIN TRANSACTION;

    INSERT INTO DBO.[PERFIL_TELA_PERMISSAO] ([CODIGO_PERFIL], [CODIGO_TELA], [PODE_VISUALIZAR], [PODE_INCLUIR], [PODE_EDITAR], [PODE_EXCLUIR], [PODE_EXPORTAR])
    SELECT G.[CODIGO_PERFIL], @FIN, G.[PODE_VISUALIZAR], 0, G.[PODE_EDITAR], 0, G.[PODE_VISUALIZAR]
    FROM DBO.[PERFIL_TELA_PERMISSAO] AS G
    WHERE G.[CODIGO_TELA] = @GUIAS
      AND NOT EXISTS (SELECT 1 FROM DBO.[PERFIL_TELA_PERMISSAO] AS N WHERE N.[CODIGO_PERFIL] = G.[CODIGO_PERFIL] AND N.[CODIGO_TELA] = @FIN);

    DISABLE TRIGGER TRG_PERFIL_TELA_PERMISSAO_PROTEGIDO ON DBO.[PERFIL_TELA_PERMISSAO];
    DELETE FROM DBO.[PERFIL_TELA_PERMISSAO] WHERE [CODIGO_TELA] = @GUIAS;
    ENABLE TRIGGER TRG_PERFIL_TELA_PERMISSAO_PROTEGIDO ON DBO.[PERFIL_TELA_PERMISSAO];

    DELETE FROM DBO.[TELA_SISTEMA] WHERE [ID_TELA_SISTEMA] = @GUIAS;

    COMMIT TRANSACTION;
    PRINT 'TELA ANTIGA REMOVIDA. LIBERACOES COPIADAS PARA FATURAMENTO.FINANCEIRO.';
END;
GO
