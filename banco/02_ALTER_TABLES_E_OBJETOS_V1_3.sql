IF DATABASE_PRINCIPAL_ID('ROLE_DBA_CORRECAO')   IS NULL CREATE ROLE ROLE_DBA_CORRECAO;      -- CORRECOES EXCEPCIONAIS DO PRONTUARIO
GO
GRANT SELECT, INSERT, UPDATE ON SCHEMA::DBO TO ROLE_APP_AGENDAMENTO;
-- A APLICACAO SO APAGA LINHAS DE PERMISSOES E DE PERFIL SEM USUARIO (RN21); OS GATILHOS PROTEGEM O ADMINISTRADOR.
GRANT DELETE ON DBO.[PERFIL_ACESSO]          TO ROLE_APP_AGENDAMENTO;
GRANT DELETE ON DBO.[PERFIL_TELA_PERMISSAO]  TO ROLE_APP_AGENDAMENTO;
GRANT DELETE ON DBO.[PERFIL_CAMPO_PERMISSAO] TO ROLE_APP_AGENDAMENTO;
GRANT EXECUTE ON DBO.USP_CONSULTA_CRIAR            TO ROLE_APP_AGENDAMENTO;
GRANT EXECUTE ON DBO.USP_CONSULTA_ALTERAR_HORARIO  TO ROLE_APP_AGENDAMENTO;
-- SOMENTE INCLUSAO:
DENY UPDATE, DELETE ON DBO.[LOG_AUDITORIA]               TO ROLE_APP_AGENDAMENTO;
DENY UPDATE, DELETE ON DBO.[CONSULTA_STATUS_HISTORICO]   TO ROLE_APP_AGENDAMENTO;
DENY UPDATE, DELETE ON DBO.[CONSENTIMENTO_LGPD]          TO ROLE_APP_AGENDAMENTO;
DENY UPDATE, DELETE ON DBO.[REGISTRO_PRONTUARIO]         TO ROLE_APP_AGENDAMENTO;
DENY UPDATE, DELETE ON DBO.[PRONTUARIO_CORRECAO]         TO ROLE_APP_AGENDAMENTO;
-- A APLICACAO NAO ESCREVE EM PRONTUARIO_CORRECAO (SO O GATILHO, EXECUTADO NA CORRECAO DO DBA):
DENY INSERT ON DBO.[PRONTUARIO_CORRECAO] TO ROLE_APP_AGENDAMENTO;
-- QUEM FAZ A CORRECAO EXCEPCIONAL (MEMBRO DESTA ROLE):
GRANT SELECT, UPDATE ON DBO.[REGISTRO_PRONTUARIO] TO ROLE_DBA_CORRECAO;
GRANT SELECT, INSERT ON DBO.[PRONTUARIO_CORRECAO] TO ROLE_DBA_CORRECAO;
GRANT INSERT ON DBO.[LOG_AUDITORIA] TO ROLE_DBA_CORRECAO;
GO
