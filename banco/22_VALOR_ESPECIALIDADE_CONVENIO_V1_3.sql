-- =====================================================================
-- SCRIPT 22 - VALOR DA CONSULTA POR ESPECIALIDADE NO CADASTRO DO CONVENIO (V1.3)
-- CADA ESPECIALIDADE DO CONVENIO (DBO.CONVENIO_ESPECIALIDADE) GANHA O SEU VALOR DE CONSULTA (COLUNA VALOR).
-- O CREDENCIAMENTO (POR UNIDADE) PODE TER VALOR PROPRIO (DBO.CREDENCIAMENTO_CONVENIO.VALOR, SCRIPT 21);
-- QUANDO ESTE FICA 0, VALE O VALOR DA ESPECIALIDADE NO CONVENIO.
-- PODE SER EXECUTADO MAIS DE UMA VEZ. EXECUTAR DEPOIS DOS SCRIPTS 19, 20 E 21.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.CONVENIO_ESPECIALIDADE', 'VALOR') IS NULL
    ALTER TABLE DBO.CONVENIO_ESPECIALIDADE ADD [VALOR] DECIMAL(10,2) NOT NULL
        CONSTRAINT DF_CONVENIO_ESPECIALIDADE_VALOR DEFAULT (0);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.CHECK_CONSTRAINTS WHERE NAME = 'CK_CONVENIO_ESPECIALIDADE_VALOR')
    ALTER TABLE DBO.CONVENIO_ESPECIALIDADE ADD CONSTRAINT CK_CONVENIO_ESPECIALIDADE_VALOR CHECK ([VALOR] >= 0);
GO

-- VALORES JA EXISTENTES: PRIMEIRO O DO CREDENCIAMENTO (O MAIOR DA ESPECIALIDADE), DEPOIS O ANTIGO DO CONVENIO.
UPDATE CE SET CE.VALOR = X.VALOR
FROM DBO.CONVENIO_ESPECIALIDADE CE
JOIN (SELECT CODIGO_CONVENIO, CODIGO_ESPECIALIDADE, MAX(VALOR) AS VALOR FROM DBO.CREDENCIAMENTO_CONVENIO GROUP BY CODIGO_CONVENIO, CODIGO_ESPECIALIDADE) X
  ON X.CODIGO_CONVENIO = CE.CODIGO_CONVENIO AND X.CODIGO_ESPECIALIDADE = CE.CODIGO_ESPECIALIDADE
WHERE CE.VALOR = 0 AND X.VALOR > 0;
GO

IF COL_LENGTH('DBO.CONVENIO', 'VALOR_CONSULTA') IS NOT NULL
    EXEC (N'UPDATE CE SET CE.VALOR = C.VALOR_CONSULTA
            FROM DBO.CONVENIO_ESPECIALIDADE CE JOIN DBO.CONVENIO C ON C.CODIGO_CONVENIO = CE.CODIGO_CONVENIO
            WHERE CE.VALOR = 0 AND C.VALOR_CONSULTA > 0;');
GO

-- O VALOR PROPRIO DO CREDENCIAMENTO (COPIADO PELO SCRIPT 21) PASSA A SER IGUAL AO DA ESPECIALIDADE; ZERA PARA VALER O DO CONVENIO.
UPDATE K SET K.VALOR = 0
FROM DBO.CREDENCIAMENTO_CONVENIO K
JOIN DBO.CONVENIO_ESPECIALIDADE CE ON CE.CODIGO_CONVENIO = K.CODIGO_CONVENIO AND CE.CODIGO_ESPECIALIDADE = K.CODIGO_ESPECIALIDADE
WHERE K.VALOR = CE.VALOR AND K.VALOR > 0;
GO

SELECT C.CODIGO_CONVENIO, C.RAZAO_SOCIAL, E.NOME AS ESPECIALIDADE, CE.VALOR
FROM DBO.CONVENIO_ESPECIALIDADE CE
JOIN DBO.CONVENIO C ON C.CODIGO_CONVENIO = CE.CODIGO_CONVENIO
JOIN DBO.ESPECIALIDADE E ON E.CODIGO_ESPECIALIDADE = CE.CODIGO_ESPECIALIDADE
ORDER BY C.RAZAO_SOCIAL, E.NOME;
GO
