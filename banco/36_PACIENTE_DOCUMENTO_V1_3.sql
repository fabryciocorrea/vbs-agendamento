USE VBSAGENDA;
GO

IF OBJECT_ID('DBO.PACIENTE_DOCUMENTO') IS NULL
CREATE TABLE DBO.[PACIENTE_DOCUMENTO] (
    [CODIGO_PACIENTE_DOCUMENTO] BIGINT IDENTITY(1,1) NOT NULL,
    [CODIGO_PUBLIC] UNIQUEIDENTIFIER NOT NULL,
    [CODIGO_PACIENTE] INT NOT NULL,
    [TIPO_DOCUMENTO] VARCHAR(20) NOT NULL,
    [DESCRICAO] NVARCHAR(150) NULL,
    [NOME_ARQUIVO] NVARCHAR(255) NOT NULL,
    [TIPO_CONTEUDO] VARCHAR(60) NOT NULL,
    [TAMANHO_BYTES] INT NOT NULL,
    [HASH_SHA256] CHAR(64) NOT NULL,
    [CONTEUDO] VARBINARY(MAX) NOT NULL,
    [CODIGO_USUARIO] INT NOT NULL,
    [DATA_HORA] DATETIME2(0) NOT NULL CONSTRAINT DF_PACIENTE_DOCUMENTO_DATA_HORA DEFAULT SYSUTCDATETIME(),
    CONSTRAINT PK_PACIENTE_DOCUMENTO PRIMARY KEY ([CODIGO_PACIENTE_DOCUMENTO]),
    CONSTRAINT UQ_PACIENTE_DOCUMENTO_CODIGO_PUBLIC UNIQUE ([CODIGO_PUBLIC]),
    CONSTRAINT CK_PACIENTE_DOCUMENTO_TIPO CHECK ([TIPO_DOCUMENTO] IN ('IDENTIDADE','ENCAMINHAMENTO','AUTORIZACAO','CARTEIRINHA','EXAME','OUTRO')),
    CONSTRAINT CK_PACIENTE_DOCUMENTO_TIPO_CONTEUDO CHECK ([TIPO_CONTEUDO] IN ('application/pdf','image/jpeg','image/png')),
    CONSTRAINT CK_PACIENTE_DOCUMENTO_TAMANHO CHECK ([TAMANHO_BYTES] BETWEEN 1 AND 5242880),
    CONSTRAINT FK_PACIENTE_DOCUMENTO_CODIGO_PACIENTE FOREIGN KEY ([CODIGO_PACIENTE]) REFERENCES DBO.[PACIENTE] ([CODIGO_PACIENTE]),
    CONSTRAINT FK_PACIENTE_DOCUMENTO_CODIGO_USUARIO FOREIGN KEY ([CODIGO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO])
);
GO

IF NOT EXISTS (SELECT 1 FROM SYS.INDEXES WHERE NAME = 'IX_PACIENTE_DOCUMENTO_PACIENTE' AND OBJECT_ID = OBJECT_ID('DBO.PACIENTE_DOCUMENTO'))
    CREATE INDEX IX_PACIENTE_DOCUMENTO_PACIENTE ON DBO.[PACIENTE_DOCUMENTO] ([CODIGO_PACIENTE], [DATA_HORA] DESC);
GO

GRANT SELECT, INSERT, DELETE ON DBO.[PACIENTE_DOCUMENTO] TO ROLE_APP_AGENDAMENTO;
GRANT SELECT ON DBO.[PACIENTE_DOCUMENTO] TO ROLE_DBA_CORRECAO;
GO

