-- =====================================================================
-- SCRIPT 12 - NUMERO E COMPLEMENTO DO ENDERECO (V1.3)
-- TABELAS: PACIENTE, PROFISSIONAL, COLABORADOR_PRESTADOR
-- NUMERO: OBRIGATORIO (ATE 10 CARACTERES). ENDERECO SEM NUMERO = 'S/N'.
-- COMPLEMENTO: OPCIONAL (ATE 60 CARACTERES).
-- LINHAS JA EXISTENTES (DADOS DE TESTE) RECEBEM 'S/N' E PODEM SER CORRIGIDAS PELA TELA.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

-- PACIENTE
IF COL_LENGTH('DBO.PACIENTE', 'NUMERO') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [NUMERO] NVARCHAR(10) NOT NULL CONSTRAINT DF_PACIENTE_NUMERO DEFAULT 'S/N';
IF COL_LENGTH('DBO.PACIENTE', 'COMPLEMENTO') IS NULL
    ALTER TABLE DBO.PACIENTE ADD [COMPLEMENTO] NVARCHAR(60) NULL;
GO
IF EXISTS (SELECT 1 FROM SYS.DEFAULT_CONSTRAINTS WHERE NAME = 'DF_PACIENTE_NUMERO')
    ALTER TABLE DBO.PACIENTE DROP CONSTRAINT DF_PACIENTE_NUMERO;
GO

-- PROFISSIONAL
IF COL_LENGTH('DBO.PROFISSIONAL', 'NUMERO') IS NULL
    ALTER TABLE DBO.PROFISSIONAL ADD [NUMERO] NVARCHAR(10) NOT NULL CONSTRAINT DF_PROFISSIONAL_NUMERO DEFAULT 'S/N';
IF COL_LENGTH('DBO.PROFISSIONAL', 'COMPLEMENTO') IS NULL
    ALTER TABLE DBO.PROFISSIONAL ADD [COMPLEMENTO] NVARCHAR(60) NULL;
GO
IF EXISTS (SELECT 1 FROM SYS.DEFAULT_CONSTRAINTS WHERE NAME = 'DF_PROFISSIONAL_NUMERO')
    ALTER TABLE DBO.PROFISSIONAL DROP CONSTRAINT DF_PROFISSIONAL_NUMERO;
GO

-- COLABORADOR_PRESTADOR
IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'NUMERO') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [NUMERO] NVARCHAR(10) NOT NULL CONSTRAINT DF_COLABORADOR_PRESTADOR_NUMERO DEFAULT 'S/N';
IF COL_LENGTH('DBO.COLABORADOR_PRESTADOR', 'COMPLEMENTO') IS NULL
    ALTER TABLE DBO.COLABORADOR_PRESTADOR ADD [COMPLEMENTO] NVARCHAR(60) NULL;
GO
IF EXISTS (SELECT 1 FROM SYS.DEFAULT_CONSTRAINTS WHERE NAME = 'DF_COLABORADOR_PRESTADOR_NUMERO')
    ALTER TABLE DBO.COLABORADOR_PRESTADOR DROP CONSTRAINT DF_COLABORADOR_PRESTADOR_NUMERO;
GO

-- CONFERENCIA
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE COLUMN_NAME IN ('NUMERO', 'COMPLEMENTO')
  AND TABLE_NAME IN ('PACIENTE', 'PROFISSIONAL', 'COLABORADOR_PRESTADOR')
ORDER BY TABLE_NAME, COLUMN_NAME;
GO
