-- =====================================================================
-- SCRIPT 15 - ENDERECO E ESCOLARIDADE DO RESPONSAVEL LEGAL (V1.3)
-- O RESPONSAVEL LEGAL PASSA A TER OS MESMOS DADOS PESSOAIS DO PACIENTE (ENDERECO, NUMERO, COMPLEMENTO,
-- CIDADE, UF E ESCOLARIDADE). AS COLUNAS ACEITAM NULO PARA NAO ALTERAR OS RESPONSAVEIS JA CADASTRADOS
-- (DADOS DE TESTE); O SISTEMA EXIGE OS CAMPOS NO CADASTRO E NA ALTERACAO.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF COL_LENGTH('DBO.RESPONSAVEL_LEGAL', 'ENDERECO') IS NULL     ALTER TABLE DBO.RESPONSAVEL_LEGAL ADD [ENDERECO] NVARCHAR(250) NULL;
IF COL_LENGTH('DBO.RESPONSAVEL_LEGAL', 'NUMERO') IS NULL       ALTER TABLE DBO.RESPONSAVEL_LEGAL ADD [NUMERO] NVARCHAR(10) NULL;
IF COL_LENGTH('DBO.RESPONSAVEL_LEGAL', 'COMPLEMENTO') IS NULL  ALTER TABLE DBO.RESPONSAVEL_LEGAL ADD [COMPLEMENTO] NVARCHAR(60) NULL;
IF COL_LENGTH('DBO.RESPONSAVEL_LEGAL', 'CIDADE') IS NULL       ALTER TABLE DBO.RESPONSAVEL_LEGAL ADD [CIDADE] NVARCHAR(80) NULL;
IF COL_LENGTH('DBO.RESPONSAVEL_LEGAL', 'UF') IS NULL           ALTER TABLE DBO.RESPONSAVEL_LEGAL ADD [UF] CHAR(2) NULL;
IF COL_LENGTH('DBO.RESPONSAVEL_LEGAL', 'ESCOLARIDADE') IS NULL ALTER TABLE DBO.RESPONSAVEL_LEGAL ADD [ESCOLARIDADE] NVARCHAR(40) NULL;
GO

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'RESPONSAVEL_LEGAL'
ORDER BY ORDINAL_POSITION;
GO
