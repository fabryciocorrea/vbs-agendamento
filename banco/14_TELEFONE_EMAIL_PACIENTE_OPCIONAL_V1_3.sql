-- =====================================================================
-- SCRIPT 14 - TELEFONE E E-MAIL DO PACIENTE PASSAM A SER OPCIONAIS (V1.3)
-- O PACIENTE MENOR DE IDADE PODE NAO TER TELEFONE NEM E-MAIL PROPRIOS (O CONTATO E O DO
-- RESPONSAVEL LEGAL). PARA O MAIOR DE IDADE, A OBRIGATORIEDADE CONTINUA NO SISTEMA.
-- PODE SER EXECUTADO MAIS DE UMA VEZ.
-- =====================================================================
USE VBSAGENDA;
GO

IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'PACIENTE' AND COLUMN_NAME = 'TELEFONE' AND IS_NULLABLE = 'NO')
    ALTER TABLE DBO.PACIENTE ALTER COLUMN [TELEFONE] NVARCHAR(20) NULL;
GO
IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'PACIENTE' AND COLUMN_NAME = 'EMAIL' AND IS_NULLABLE = 'NO')
    ALTER TABLE DBO.PACIENTE ALTER COLUMN [EMAIL] NVARCHAR(150) NULL;
GO

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'PACIENTE' AND COLUMN_NAME IN ('TELEFONE', 'EMAIL');
GO
