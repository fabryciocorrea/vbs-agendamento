    CONSTRAINT CK_PRONTUARIO_AUTORIZACAO_DOC_TIPO CHECK ([TIPO_CONTEUDO] IN ('application/pdf','image/jpeg','image/png')),
    CONSTRAINT CK_PRONTUARIO_AUTORIZACAO_DOC_TAMANHO CHECK ([TAMANHO_BYTES] BETWEEN 1 AND 5242880),
    CONSTRAINT FK_PRONTUARIO_AUTORIZACAO_DOC_CODIGO_PACIENTE FOREIGN KEY ([CODIGO_PACIENTE]) REFERENCES DBO.[PACIENTE] ([CODIGO_PACIENTE]),
    CONSTRAINT FK_PRONTUARIO_AUTORIZACAO_DOC_CODIGO_USUARIO FOREIGN KEY ([CODIGO_USUARIO]) REFERENCES DBO.[USUARIO] ([CODIGO_USUARIO])
);
