             2. NO AMBIENTE LOCAL, TESTAR COM PACIENTE FICTICIO: EDITAR SEM DOCUMENTO (ERRO 50066), COM DOCUMENTO (OK), E CONFERIR
                PRONTUARIO_CORRECAO.CODIGO_AUTORIZACAO_DOC E O LOG_AUDITORIA.
             3. O DOCUMENTO FICA NO BANCO (VARBINARY): INCLUIR NO BACKUP E NA POLITICA DE RETENCAO (RNF04). */
