/* ============================================================================================================
   SCRIPT 29 - EXCLUSAO DE CADASTROS PELO ADMINISTRADOR
   BANCO: VBSAGENDA (RODAR NO SSMS, DEPOIS DO SCRIPT 28)
   O QUE FAZ:
   1) RETIRA AS TRES CHAVES ESTRANGEIRAS QUE LIGAM REGISTROS DE SOMENTE INCLUSAO AO PACIENTE E AO RESPONSAVEL LEGAL
      (LOG_AUDITORIA, CONSENTIMENTO_LGPD, CONSENTIMENTO_LGPD_RESPONSAVEL). SEM ISSO NENHUM PACIENTE PODERIA SER EXCLUIDO,
      POIS O BANCO NAO PERMITE APAGAR ESSES REGISTROS. ELES CONTINUAM GUARDADOS (LOG E PROVA DE CONSENTIMENTO) E PASSAM A
      GUARDAR O CODIGO COMO NUMERO, SEM VINCULO COM UMA LINHA EXISTENTE.
   2) CONCEDE DELETE A ROLE_APP_AGENDAMENTO NAS TABELAS QUE O SISTEMA PASSA A EXCLUIR (SE A ROLE EXISTIR).
   A PROPRIA API SO EXCLUI PARA O ADMINISTRADOR E SO REGISTROS SEM HISTORICO (CONSULTA, PRONTUARIO, LISTA DE ESPERA ETC.).
   ============================================================================================================ */
SET NOCOUNT ON;
GO

IF EXISTS (SELECT 1 FROM SYS.FOREIGN_KEYS WHERE [NAME] = 'FK_LOG_AUDITORIA_CODIGO_PACIENTE')
    ALTER TABLE DBO.[LOG_AUDITORIA] DROP CONSTRAINT FK_LOG_AUDITORIA_CODIGO_PACIENTE;
IF EXISTS (SELECT 1 FROM SYS.FOREIGN_KEYS WHERE [NAME] = 'FK_CONSENTIMENTO_LGPD_CODIGO_PACIENTE')
    ALTER TABLE DBO.[CONSENTIMENTO_LGPD] DROP CONSTRAINT FK_CONSENTIMENTO_LGPD_CODIGO_PACIENTE;
IF EXISTS (SELECT 1 FROM SYS.FOREIGN_KEYS WHERE [NAME] = 'FK_CONSENTIMENTO_LGPD_RESPONSAVEL_CODIGO_RESPONSAVEL')
    ALTER TABLE DBO.[CONSENTIMENTO_LGPD_RESPONSAVEL] DROP CONSTRAINT FK_CONSENTIMENTO_LGPD_RESPONSAVEL_CODIGO_RESPONSAVEL;
GO

IF DATABASE_PRINCIPAL_ID('ROLE_APP_AGENDAMENTO') IS NOT NULL
BEGIN
    GRANT DELETE ON DBO.[PACIENTE]                         TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[RESPONSAVEL_LEGAL]                TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[PACIENTE_PROFISSIONAL_HISTORICO]  TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[CONVENIO]                         TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[CONVENIO_ESPECIALIDADE]           TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[CREDENCIAMENTO_CONVENIO]          TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[FORMA_PAGAMENTO]                  TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[PROFISSIONAL]                     TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[PROFISSIONAL_ESPECIALIDADE]       TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[PROFISSIONAL_UNIDADE]             TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[PROFISSIONAL_HORARIO]             TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[COLABORADOR_PRESTADOR]            TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[ESPECIALIDADE]                    TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[UNIDADE]                          TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[SALA]                             TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[USUARIO]                          TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[TOKEN_RECUPERACAO_SENHA]          TO ROLE_APP_AGENDAMENTO;
    GRANT DELETE ON DBO.[SESSAO_USUARIO]                   TO ROLE_APP_AGENDAMENTO;
END;
GO

/* CONFERENCIA: NAO DEVE LISTAR NENHUMA DAS TRES CHAVES. */
SELECT [NAME] AS [CHAVE_AINDA_EXISTE] FROM SYS.FOREIGN_KEYS
WHERE [NAME] IN ('FK_LOG_AUDITORIA_CODIGO_PACIENTE', 'FK_CONSENTIMENTO_LGPD_CODIGO_PACIENTE', 'FK_CONSENTIMENTO_LGPD_RESPONSAVEL_CODIGO_RESPONSAVEL');
GO
